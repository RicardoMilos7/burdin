//! `burdin vendor`: copies the git packages of a graph into `vendor/` so a build can run offline (`spec/packages.md`,
//! PKG23-PKG24).
//!
//! ```text
//! <dir>/vendor/burdin-vendor.txt   the names this command wrote: a header comment, then one name per line
//! <dir>/vendor/<name>/             a git package in full: the files its checksum covers (PKG7)
//! ```
//!
//! The directory belongs to burdin only through that list: a run removes the directories the list names and never
//! touches any other entry of `vendor/`.

use crate::resolve;
use burdin_query::lockfile::{self, LockedPackage};
use burdin_query::package::source_path_text;
use burdin_query::workspace;
use std::path::{Path, PathBuf};

/// The file in `vendor/` that names the packages this command wrote.
pub const LIST_FILE: &str = "burdin-vendor.txt";

/// The first line of [`LIST_FILE`].
const HEADER: &str = "# burdin-vendor.txt: the packages `burdin vendor` wrote here. It is generated by burdin;\n\
                      # `burdin vendor` removes the directories named below and nothing else in vendor/.\n";

/// The names of the packages copied into `<dir>/vendor/` by one run, in lockfile order.
#[derive(Debug, PartialEq, Eq)]
pub struct Vendored {
    pub names: Vec<String>,
    /// The `vendor` directory.
    pub dir: PathBuf,
}

/// Resolves the graph of the package in `dir` (writing `burdin.lock` when a build would) and copies each git package
/// into `dir/vendor/<name>`, checked against the lockfile's checksum (PKG23). Official and path packages are not
/// copied. Refuses, before it removes anything, a `vendor/<name>` that the list file does not name.
pub fn vendor(dir: &Path) -> Result<Vendored, String> {
    resolve::sync(dir, false)?;
    // A workspace vendors once, at its root, beside the lockfile an offline build reads (`spec/workspaces.md`, WS14).
    let root = workspace::lock_dir(dir)?;
    let locked: Vec<LockedPackage> = lockfile::read(&root)?.map(|lock| lock.packages).unwrap_or_default();
    let packages: Vec<&LockedPackage> = locked.iter().filter(|p| p.git.is_some()).collect();
    let vendor_dir = root.join("vendor");
    let listed = read_list(&vendor_dir)?;

    for package in &packages {
        let target = vendor_dir.join(&package.name);
        if target.exists() && !listed.contains(&package.name) {
            return Err(format!(
                "{} exists and was not written by `burdin vendor`: move it aside, then run the command again",
                source_path_text(&target)
            ));
        }
    }
    for name in &listed {
        remove_if_exists(&vendor_dir.join(name))?;
    }
    let names: Vec<String> = packages.iter().map(|p| p.name.clone()).collect();
    if names.is_empty() {
        remove_if_exists(&vendor_dir.join(LIST_FILE))?;
        return Ok(Vendored { names, dir: vendor_dir });
    }

    // The list is written before the copies, so a run that stops halfway leaves nothing unlisted for the next run to
    // refuse.
    std::fs::create_dir_all(&vendor_dir)
        .map_err(|e| format!("cannot create {}: {e}", source_path_text(&vendor_dir)))?;
    write_list(&vendor_dir, &names)?;
    for package in &packages {
        let Some(git) = &package.git else { continue };
        let source = lockfile::git_checkout_dir(&git.url, &git.commit)?;
        let target = vendor_dir.join(&package.name);
        copy_tree(&source, &target)?;
        let found = resolve::checksum(&target)?;
        if package.checksum.as_deref() != Some(found.as_str()) {
            let _ = std::fs::remove_dir_all(&target);
            return Err(format!(
                "the files of `{}` ({} at {}) do not match burdin.lock: expected {}, found {found}; the checkout at {} \
                 was changed, so delete it to fetch it again",
                package.name,
                git.url,
                git.commit,
                package.checksum.as_deref().unwrap_or("no checksum"),
                source_path_text(&source)
            ));
        }
    }
    Ok(Vendored { names, dir: vendor_dir })
}

/// Copies the files of the package at `source` into `target`, leaving out the top-level `.git` and `target`
/// directories exactly as the checksum does (PKG7), so a copy has the same checksum as its checkout.
pub(crate) fn copy_tree(source: &Path, target: &Path) -> Result<(), String> {
    copy_dir(source, target, true)
}

fn copy_dir(source: &Path, target: &Path, top: bool) -> Result<(), String> {
    std::fs::create_dir_all(target).map_err(|e| format!("cannot create {}: {e}", source_path_text(target)))?;
    let entries = std::fs::read_dir(source).map_err(|e| format!("cannot read {}: {e}", source_path_text(source)))?;
    for entry in entries {
        let entry = entry.map_err(|e| format!("cannot read {}: {e}", source_path_text(source)))?;
        let name = entry.file_name();
        if top && (name == ".git" || name == "target") {
            continue;
        }
        let from = entry.path();
        let to = target.join(&name);
        if from.is_dir() {
            copy_dir(&from, &to, false)?;
        } else {
            std::fs::copy(&from, &to).map_err(|e| format!("cannot copy {}: {e}", source_path_text(&from)))?;
        }
    }
    Ok(())
}

/// The names [`LIST_FILE`] lists; none when there is no list.
fn read_list(vendor_dir: &Path) -> Result<Vec<String>, String> {
    let path = vendor_dir.join(LIST_FILE);
    if !path.is_file() {
        return Ok(Vec::new());
    }
    let text = std::fs::read_to_string(&path).map_err(|e| format!("cannot read {}: {e}", source_path_text(&path)))?;
    Ok(text.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')).map(str::to_string).collect())
}

fn write_list(vendor_dir: &Path, names: &[String]) -> Result<(), String> {
    let mut text = HEADER.to_string();
    for name in names {
        text.push_str(name);
        text.push('\n');
    }
    let path = vendor_dir.join(LIST_FILE);
    std::fs::write(&path, text).map_err(|e| format!("cannot write {}: {e}", source_path_text(&path)))
}

fn remove_if_exists(path: &Path) -> Result<(), String> {
    if path.is_dir() {
        std::fs::remove_dir_all(path).map_err(|e| format!("cannot remove {}: {e}", source_path_text(path)))?;
    } else if path.exists() {
        std::fs::remove_file(path).map_err(|e| format!("cannot remove {}: {e}", source_path_text(path)))?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_list_reads_back_what_it_wrote() {
        let dir = std::env::temp_dir().join(format!("burdin-vendor-list-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        write_list(&dir, &["colors".to_string(), "greet".to_string()]).unwrap();
        assert_eq!(read_list(&dir).unwrap(), ["colors", "greet"]);
        assert!(std::fs::read_to_string(dir.join(LIST_FILE)).unwrap().starts_with("# burdin-vendor.txt"));
        std::fs::remove_dir_all(&dir).unwrap();
        // No list is no names.
        assert_eq!(read_list(&dir).unwrap(), Vec::<String>::new());
    }
}
