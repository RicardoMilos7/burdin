//! Generated inputs and the compilation pipeline shared by the compiler benchmarks.
//!
//! `benches/compiler.rs` times the four stages of the compiler (lexing, parsing, name resolution and type
//! checking, and code generation) over programs produced by [`generate`]. The inputs are generated instead of
//! checked in so that a size is the only parameter of a measurement: changing the generator changes every
//! number, which is why it stays deliberately plain and deterministic.
//!
//! The programs need no standard library: they use only built-in types and methods (`List`, `String`,
//! `println`, integer `to_string`), so sema spends its time on the measured program and not on checking `std`
//! once per iteration.

use std::collections::{HashMap, HashSet};
use std::fmt::Write as _;
use std::time::Duration;

use burdin_diag::{Diagnostics, FileId, SourceMap};
use burdin_syntax::ast;
use burdin_syntax::lexer::{self, LexResult};
use burdin_syntax::token::Token;
use burdin_tir::Program;

/// A generated program after lexing and parsing, ready to be checked more than once.
pub struct Generated {
    /// The source text of the program.
    pub text: String,
    /// The source map the AST spans point into.
    pub sources: SourceMap,
    pub file: FileId,
    pub ast: ast::File,
    /// The lexed token stream, kept so the parser can be timed without the lexer.
    pub tokens: Vec<Token>,
    pub truncated: bool,
}

/// Builds a deterministic, valid Burdin program with `units` independent chunks. Each chunk declares a struct
/// with methods, an enum with a `match`, a generic function, an arithmetic loop, a `List` loop, and a `String`
/// loop; `main` calls the arithmetic and enum functions so the program has a real entry point.
pub fn generate(units: usize) -> String {
    let mut src = String::new();
    src.push_str("// Generated by burdin_bench::generate. Do not edit.\n");
    write_chunks(&mut src, units, "");
    src.push_str("fn main() {\n    let mut acc: i64 = 0\n");
    for i in 0..units {
        write!(src, "    acc = acc + fold{i}(3)\n    acc = acc + kind{i}(K{i}.Pair(1, 2))\n")
            .expect("writing to a String cannot fail");
    }
    src.push_str("    println(acc.to_string())\n}\n");
    src
}

/// A generated package of `files` modules, each holding `units` chunks: `main.bd` with the entry point and
/// `module1.bd`, `module2.bd`, ... without one. Every item name carries the module's number, so the modules do
/// not shadow each other in the prelude. This is the input of the incremental benchmarks: a package big enough
/// that a keystroke cannot afford to recheck all of it.
pub fn generate_package(files: usize, units: usize) -> Vec<(String, String)> {
    let mut out = vec![("main.bd".to_string(), generate(units))];
    for file in 1..files.max(1) {
        let mut src = String::new();
        src.push_str("// Generated by burdin_bench::generate_package. Do not edit.\n");
        write_chunks(&mut src, units, &format!("M{file}_"));
        out.push((format!("module{file}.bd"), src));
    }
    out
}

/// The chunks of [`generate`], with every item name starting with `tag`.
fn write_chunks(src: &mut String, units: usize, tag: &str) {
    for i in 0..units {
        write!(
            src,
            "\
struct V{tag}{i}: Copy, Clone, Eq {{
    a: i32
    b: i64
    on: bool
}}

enum K{tag}{i} {{
    Unit
    Pair(i32, i64)
    Record {{ x: i32, on: bool }}
}}

V{tag}{i} {{
    fn new(a: i32, b: i64, on: bool): V{tag}{i} {{
        V{tag}{i} {{ a, b, on }}
    }}

    fn total(self): i64 {{
        self.a as i64 + self.b
    }}

    fn bump(mut self, by: i32) {{
        self.a = self.a + by
    }}
}}

fn kind{tag}{i}(value: K{tag}{i}): i64 {{
    match value {{
        K{tag}{i}.Unit => 0,
        K{tag}{i}.Pair(x, y) => x as i64 + y,
        K{tag}{i}.Record {{ x, on }} => if on {{ x as i64 }} else {{ 0 - x as i64 }},
    }}
}}

fn maxv{tag}{i}<T: Ord>(own a: T, own b: T): T {{
    if a > b {{ a }} else {{ b }}
}}

fn fold{tag}{i}(n: i32): i64 {{
    let mut total: i64 = 0
    let mut k = 0
    while k < n {{
        let v = V{tag}{i}.new(k, k as i64, k % 2 == 0)
        total = total + v.total()
        let w = maxv{tag}{i}(k, 0 - k)
        total = total + w as i64
        k = k + 1
    }}
    total
}}

fn list{tag}{i}(n: i32): i32 {{
    let mut xs = List<i32>.new()
    let mut k = 0
    while k < n {{
        xs.push(k)
        k = k + 1
    }}
    let mut sum = 0
    for x in xs {{
        sum = sum + x
    }}
    sum
}}

fn text{tag}{i}(n: i32): usize {{
    let mut s = String.new()
    let mut k = 0
    while k < n {{
        s.push_str(\"ab\")
        k = k + 1
    }}
    s.len()
}}

"
        )
        .expect("writing to a String cannot fail");
    }
}

/// Lexes and parses the generated program. Panics if the input does not parse, because that means the benchmark
/// generator itself is broken (the conformance suite covers the compiler's diagnostics).
pub fn parse_generated(units: usize) -> Generated {
    let text = generate(units);
    let mut sources = SourceMap::default();
    let file = sources.add("bench.bd".to_string(), text.clone());
    let mut diags = Diagnostics::default();
    let lexed = lexer::lex(file, &text, &mut diags);
    let ast = burdin_syntax::parser::parse_file(
        file,
        LexResult { tokens: lexed.tokens.clone(), truncated: lexed.truncated },
        &mut diags,
    );
    assert!(!diags.has_errors(), "the generated benchmark input does not parse:\n{}", diags.render(&sources));
    Generated { text, sources, file, ast, tokens: lexed.tokens, truncated: lexed.truncated }
}

/// Runs name resolution and type checking over a parsed program. The program is a one-module package with no
/// dependencies, so no `std` package is declared and the prelude is empty.
pub fn check(generated: &Generated) -> (Program, Diagnostics) {
    let packages = [burdin_sema::Package {
        name: "bench".to_string(),
        is_root: true,
        deps: Vec::new(),
        root_module: Some(0),
        official: Vec::new(),
        modules: vec![burdin_sema::Module { file: generated.file, path: Vec::new(), ast: &generated.ast }],
    }];
    let mut diags = Diagnostics::default();
    // The generated programs have no standard library and record no trace frames.
    let program =
        burdin_sema::check(&packages, 0, 0, burdin_sema::EntryMode::Build, false, &generated.sources, &mut diags);
    (program, diags)
}

/// Runs the memory checks (return origins, moves and drops, borrows) over a checked program.
pub fn check_memory(program: &mut Program) -> Diagnostics {
    let mut diags = Diagnostics::default();
    burdin_check::check(program, &mut diags);
    diags
}

/// Emits native object files for a checked program. This is the debug-profile path of `burdin build` (LLVM
/// optimization level `None`), split into codegen units and compiled on every core exactly like a build.
/// Only `object` is left behind: the objects of the other codegen units are removed again.
pub fn emit(program: &Program, sources: &SourceMap, object: &std::path::Path) -> Result<(), String> {
    let objects = burdin_codegen::emit_object(program, sources, "bench", object, &burdin_codegen::Options::default())?;
    for extra in objects.iter().filter(|path| path.as_path() != object) {
        let _ = std::fs::remove_file(extra);
    }
    Ok(())
}

/// Formats a generated program with `burdin fmt`'s formatter, which checks its own output, and returns the result.
pub fn format(text: &str) -> String {
    burdin_fmt::format_source(text, &burdin_fmt::Options::default()).expect("the generated program formats")
}

// --- Baselines ---------------------------------------------------------------------------------
//
// `cargo bench -p burdin_bench -- --save FILE` writes the medians of a run in the format below, and
// `--baseline FILE` compares a later run with them. The file is deliberately plain text: a developer can
// read it, CI can cache it, and the only edit it ever needs is moving a number.

/// The first line of a saved baseline, documenting the format for whoever opens the file.
pub const BASELINE_HEADER: &str =
    "# Burdin compiler benchmark baseline (format 1: case<TAB>median nanoseconds per iteration).";

/// One benchmark case and its median time per iteration.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Measurement {
    pub case: String,
    pub median: Duration,
}

/// One case present in both the baseline and the current run.
#[derive(Clone, Debug, PartialEq)]
pub struct Change {
    pub case: String,
    pub baseline: Duration,
    pub current: Duration,
    /// The current median relative to the baseline, in percent (100 is unchanged).
    pub ratio_percent: f64,
    /// Whether the case is slower than the comparison threshold allows.
    pub regressed: bool,
}

/// The result of comparing a run with a stored baseline.
#[derive(Clone, Debug, PartialEq)]
pub struct Comparison {
    /// The cases in both files, in baseline order.
    pub changes: Vec<Change>,
    /// The baseline cases this run did not measure (a filtered run leaves cases out).
    pub missing: Vec<String>,
    /// The measured cases the baseline does not contain.
    pub new: Vec<String>,
}

impl Comparison {
    /// The number of cases over the threshold; zero means the run is within the baseline.
    pub fn regression_count(&self) -> usize {
        self.changes.iter().filter(|change| change.regressed).count()
    }
}

/// Writes the measurements in the baseline format: the header comment, then one
/// `case<TAB>nanoseconds` line per case, in the order given.
pub fn render_baseline(measurements: &[Measurement]) -> String {
    let mut text = String::from(BASELINE_HEADER);
    text.push('\n');
    for measurement in measurements {
        writeln!(text, "{}\t{}", measurement.case, measurement.median.as_nanos())
            .expect("writing to a String cannot fail");
    }
    text
}

/// Reads the baseline format. Blank lines and `#` comments are ignored, so a baseline can carry notes.
/// Duplicate cases, an empty file, and malformed lines are errors: a silently mangled baseline would
/// compare the wrong numbers.
pub fn parse_baseline(text: &str) -> Result<Vec<Measurement>, String> {
    let mut measurements = Vec::new();
    let mut seen: HashSet<&str> = HashSet::new();
    for (index, line) in text.lines().enumerate() {
        let line = line.trim_end_matches('\r');
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let number = index + 1;
        let (case, nanos) =
            line.split_once('\t').ok_or_else(|| format!("line {number}: expected 'case<TAB>nanoseconds'"))?;
        if case.is_empty() || case.chars().any(char::is_whitespace) {
            return Err(format!("line {number}: invalid case name '{case}'"));
        }
        let nanos: u64 =
            nanos.trim().parse().map_err(|_| format!("line {number}: '{nanos}' is not a nanosecond count"))?;
        if !seen.insert(case) {
            return Err(format!("line {number}: duplicate case '{case}'"));
        }
        measurements.push(Measurement { case: case.to_string(), median: Duration::from_nanos(nanos) });
    }
    if measurements.is_empty() {
        return Err("no measurements".to_string());
    }
    Ok(measurements)
}

/// Compares a run with a baseline. A case is a regression when its median is more than
/// `threshold_percent` above the baseline; exactly at the threshold is within it. Cases measured
/// without a baseline entry are reported as new, and baseline entries the run did not measure are
/// reported as missing; neither is a regression.
pub fn compare(baseline: &[Measurement], current: &[Measurement], threshold_percent: u32) -> Comparison {
    let medians: HashMap<&str, Duration> = current.iter().map(|m| (m.case.as_str(), m.median)).collect();
    let baseline_cases: HashSet<&str> = baseline.iter().map(|m| m.case.as_str()).collect();

    let mut changes = Vec::new();
    let mut missing = Vec::new();
    for stored in baseline {
        match medians.get(stored.case.as_str()) {
            Some(&now) => changes.push(change(stored, now, threshold_percent)),
            None => missing.push(stored.case.clone()),
        }
    }
    let new = current.iter().filter(|m| !baseline_cases.contains(m.case.as_str())).map(|m| m.case.clone()).collect();
    Comparison { changes, missing, new }
}

fn change(baseline: &Measurement, current: Duration, threshold_percent: u32) -> Change {
    let baseline_ns = baseline.median.as_nanos();
    let current_ns = current.as_nanos();
    let ratio_percent = if baseline_ns == 0 {
        if current_ns == 0 { 100.0 } else { f64::INFINITY }
    } else {
        current_ns as f64 / baseline_ns as f64 * 100.0
    };
    let regressed = current_ns * 100 > baseline_ns * (100 + u128::from(threshold_percent));
    Change { case: baseline.case.clone(), baseline: baseline.median, current, ratio_percent, regressed }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_inputs_parse_and_check() {
        for units in [0, 1, 8, 32] {
            let generated = parse_generated(units);
            let (program, diags) = check(&generated);
            assert!(!diags.has_errors(), "{units} chunks:\n{}", diags.render(&generated.sources));
            assert!(program.main.is_some(), "{units} chunks: the generated program has no main");
        }
    }

    #[test]
    fn generation_is_deterministic() {
        assert_eq!(generate(3), generate(3));
    }

    fn measurement(case: &str, nanos: u64) -> Measurement {
        Measurement { case: case.to_string(), median: Duration::from_nanos(nanos) }
    }

    #[test]
    fn baseline_round_trips_through_text() {
        let measurements = [measurement("lex/small", 125_345), measurement("codegen/large", 201_000_000)];
        let text = render_baseline(&measurements);
        assert!(text.starts_with(BASELINE_HEADER));
        assert_eq!(parse_baseline(&text).expect("a rendered baseline parses"), measurements);
    }

    #[test]
    fn baseline_parse_ignores_comments_and_blank_lines() {
        let text = "# a note\r\n\r\nlex/small\t42\r\nsema/large\t7\n";
        assert_eq!(
            parse_baseline(text).expect("comments and blank lines are allowed"),
            [measurement("lex/small", 42), measurement("sema/large", 7),]
        );
    }

    #[test]
    fn baseline_parse_rejects_malformed_text() {
        for text in ["", "lex/small 42", "lex/small\tfast", "lex/small\t1\nlex/small\t2", "\t5"] {
            assert!(parse_baseline(text).is_err(), "{text:?} should not parse");
        }
    }

    #[test]
    fn comparison_flags_only_cases_over_the_threshold() {
        let baseline = [measurement("same", 1_000), measurement("over", 1_000), measurement("faster", 1_000)];
        let current = [measurement("same", 1_250), measurement("over", 1_251), measurement("faster", 900)];
        let comparison = compare(&baseline, &current, 25);
        assert_eq!(comparison.changes.len(), 3);
        assert!(!comparison.changes[0].regressed, "exactly 25% is within the threshold");
        assert!(comparison.changes[1].regressed, "25.1% is over the threshold");
        assert!(!comparison.changes[2].regressed, "a faster case is never a regression");
        assert_eq!(comparison.regression_count(), 1);
        assert!((comparison.changes[1].ratio_percent - 125.1).abs() < 0.001);
    }

    #[test]
    fn comparison_reports_missing_and_new_cases() {
        let baseline = [measurement("lex/small", 1_000), measurement("sema/large", 2_000)];
        let current = [measurement("lex/small", 1_000), measurement("parse/large", 3_000)];
        let comparison = compare(&baseline, &current, 25);
        assert_eq!(comparison.changes.len(), 1);
        assert_eq!(comparison.missing, vec!["sema/large".to_string()]);
        assert_eq!(comparison.new, vec!["parse/large".to_string()]);
        assert_eq!(comparison.regression_count(), 0, "a missing or new case is not a regression");
    }
}
