//! `burdin bindgen`: C headers to Burdin declarations through libclang, and Burdin exports to a C header
//! (`spec/bindgen.md`).
//!
//! The import side loads libclang at run time ([`clang`]), walks the header ([`parse`]), and renders a module
//! ([`model`]). The export side ([`export`]) only prints; the driver reads the checked program. Nothing here depends
//! on the rest of the compiler, so the driver is the one place that decides what to do with a failure.

pub mod clang;
pub mod export;
mod macros;
pub mod model;
mod parse;

use std::path::PathBuf;

/// What to generate from one header.
pub struct Options {
    /// The header, as the user wrote it: the path is read as given and named in the output.
    pub header: PathBuf,
    /// Extra arguments for the C front end: `-I<dir>`, `-D<name>=<value>`, `--target=...`, and so on.
    pub clang_args: Vec<String>,
    /// Generate C wrappers for `static inline` functions. The text to put in the `#include` line of the wrapper file.
    pub wrappers: Option<String>,
}

/// The result of one run.
pub struct Output {
    /// The Burdin module.
    pub module: String,
    /// The C file of wrappers, whenever `Options::wrappers` was set (it is empty of functions when the header has no
    /// `static inline` function, so a build script can always compile it).
    pub wrappers: Option<String>,
    /// What was skipped or changed, one line each.
    pub warnings: Vec<String>,
}

/// Why a run failed.
#[derive(Debug)]
pub enum Error {
    /// libclang could not be loaded.
    Load(String),
    /// The header did not parse: clang's error diagnostics, one per entry.
    Parse(Vec<String>),
    /// libclang could not start parsing at all.
    Clang(String),
}

/// Reads `options.header` and generates its bindings.
pub fn generate(options: &Options) -> Result<Output, Error> {
    let clang = clang::Clang::load().map_err(Error::Load)?;
    let args = clang_args(options);
    let unit = clang.parse(&options.header, &args).map_err(Error::Clang)?;
    let errors: Vec<String> = unit.diagnostics().into_iter().filter(|d| d.is_error).map(|d| d.text).collect();
    if !errors.is_empty() {
        return Err(Error::Parse(errors));
    }
    let header = options.header.display().to_string().replace('\\', "/");
    let settings =
        parse::Settings { wrappers: options.wrappers.is_some(), long_bits: if cfg!(windows) { 32 } else { 64 } };
    let generated = parse::generate(&unit, &header, settings);
    let wrappers = match &options.wrappers {
        Some(include) => {
            let mut text = format!("/* Generated by `burdin bindgen` from `{header}`; do not edit. */\n");
            text.push_str(&format!("#include \"{include}\"\n\n"));
            for function in &generated.wrapper_source {
                text.push_str(function);
                text.push('\n');
            }
            Some(text)
        }
        None => None,
    };
    let warnings = generated.module.notes.clone();
    Ok(Output { module: generated.module.render(), wrappers, warnings })
}

/// The command line the C front end is given: `-x c`, the caller's options, and on macOS the SDK's sysroot when the
/// caller did not name one. A libclang from Homebrew has no sysroot of its own, and without it every system header
/// (`<stddef.h>`, `<stdint.h>`, ...) is reported missing (BG2).
fn clang_args(options: &Options) -> Vec<String> {
    let mut args = vec!["-x".to_string(), "c".to_string()];
    args.extend(options.clang_args.iter().cloned());
    let names_a_sysroot = args.iter().any(|arg| arg.starts_with("-isysroot") || arg.starts_with("--sysroot"));
    if cfg!(target_os = "macos")
        && !names_a_sysroot
        && let Some(sdk) = macos_sdk()
    {
        args.push("-isysroot".to_string());
        args.push(sdk);
    }
    args
}

/// The macOS SDK directory `xcrun --show-sdk-path` reports. `None` on other systems, when `xcrun` is missing or
/// fails, and when the directory it prints does not exist.
#[cfg(target_os = "macos")]
fn macos_sdk() -> Option<String> {
    let output = std::process::Command::new("xcrun").args(["--show-sdk-path"]).output().ok()?;
    if !output.status.success() {
        return None;
    }
    let path = String::from_utf8(output.stdout).ok()?.trim().to_string();
    if path.is_empty() || !std::path::Path::new(&path).is_dir() {
        return None;
    }
    Some(path)
}

#[cfg(not(target_os = "macos"))]
fn macos_sdk() -> Option<String> {
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    fn options(args: &[&str]) -> Options {
        Options {
            header: PathBuf::from("c/lib.h"),
            clang_args: args.iter().map(|arg| arg.to_string()).collect(),
            wrappers: None,
        }
    }

    #[test]
    fn the_front_end_gets_c_and_the_callers_options() {
        let args = clang_args(&options(&["-Iinc", "-DNAME=1"]));
        assert_eq!(&args[..4], ["-x", "c", "-Iinc", "-DNAME=1"]);
        // On macOS the SDK may follow, since the caller named no sysroot.
        if cfg!(target_os = "macos") {
            assert_eq!(args.len(), 6);
            assert_eq!(args[4], "-isysroot");
        } else {
            assert_eq!(args.len(), 4);
        }
    }

    #[test]
    fn off_macos_no_sysroot_is_added() {
        if !cfg!(target_os = "macos") {
            assert_eq!(clang_args(&options(&[])), ["-x", "c"]);
        }
    }

    #[test]
    fn a_sysroot_from_the_caller_is_kept() {
        let args = clang_args(&options(&["-isysroot", "/somewhere"]));
        assert_eq!(args.iter().filter(|arg| *arg == "-isysroot").count(), 1);
    }
}
