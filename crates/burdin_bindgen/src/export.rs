/// Whether a name can be a C identifier in a header: ASCII letters, digits, and underscores, not starting with a
/// digit, and not a reserved word.
pub fn is_c_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else { return false };
    (first.is_ascii_alphabetic() || first == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !C_KEYWORDS.contains(&name)
}

/// The include guard for an output file: `BURDIN_` and the file stem in capitals.
pub fn guard_for(stem: &str) -> String {
    let body: String =
        stem.chars().map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_uppercase() } else { '_' }).collect();
    format!("BURDIN_{body}_H")
}

impl ExportHeader {
    pub fn render(&self) -> String {
        let mut text = String::new();
        text.push_str("/* Generated by `burdin bindgen --export`; do not edit. */\n");
        text.push_str(&format!("#ifndef {}\n#define {}\n\n", self.guard, self.guard));
        text.push_str("#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n");
        text.push_str("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");
        for constant in &self.constants {
            text.push_str(&format!("#define {} {}\n", constant.name, constant.value));
        }
        if !self.constants.is_empty() {
            text.push('\n');
        }
        for item in self.ordered_structs() {
            if item.opaque {
                text.push_str(&format!("struct {};\n", item.name));
            } else if item.fields.is_empty() {
                text.push_str(&format!("struct {} {{ char _empty; }};\n", item.name));
            } else {
                text.push_str(&format!("struct {} {{\n", item.name));
                for (name, ty) in &item.fields {
                    text.push_str(&format!("    {};\n", ty.declare(name)));
                }
                text.push_str("};\n");
            }
            text.push_str(&format!("typedef struct {} {};\n\n", item.name, item.name));
        }
        for function in &self.functions {
            let params = if function.params.is_empty() {
                "void".to_string()
            } else {
                function.params.iter().map(|(name, ty)| ty.declare(name)).collect::<Vec<_>>().join(", ")
            };
            text.push_str(&format!("{} {}({});\n", function.ret.spelling(), function.name, params));
        }
        if !self.functions.is_empty() {
            text.push('\n');
        }
        text.push_str("#ifdef __cplusplus\n}\n#endif\n\n");
        text.push_str(&format!("#endif /* {} */\n", self.guard));
        text
    }

    /// The structs with every struct a field holds by value before it. Pointers need only a declaration, which each
    /// definition's own `struct Name;` form provides, so only by-value fields order the list.
    fn ordered_structs(&self) -> Vec<&ExportStruct> {
        let mut ordered: Vec<&ExportStruct> = Vec::new();
        let mut done: Vec<&str> = Vec::new();
        fn visit<'a>(
            header: &'a ExportHeader,
            item: &'a ExportStruct,
            ordered: &mut Vec<&'a ExportStruct>,
            done: &mut Vec<&'a str>,
        ) {
            if done.contains(&item.name.as_str()) {
                return;
            }
            done.push(&item.name);
            for (_, ty) in &item.fields {
                let mut inner = ty;
                while let CType::Array(element, _) = inner {
                    inner = element;
                }
                if let CType::Struct(name) = inner
                    && let Some(dependency) = header.structs.iter().find(|s| &s.name == name)
                {
                    visit(header, dependency, ordered, done);
                }
            }
            ordered.push(item);
        }
        for item in &self.structs {
            visit(self, item, &mut ordered, &mut done);
        }
        ordered
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn point() -> ExportStruct {
        ExportStruct {
            name: "Point".into(),
            fields: vec![("x".into(), CType::Scalar("int32_t")), ("y".into(), CType::Scalar("int32_t"))],
            opaque: false,
        }
    }

    #[test]
    fn declarators_put_pointers_and_arrays_where_c_wants_them() {
        let text = CType::Pointer(Box::new(CType::Scalar("char"))).declare("name");
        assert_eq!(text, "char *name");
        assert_eq!(CType::Pointer(Box::new(CType::Pointer(Box::new(CType::Void)))).declare("pp"), "void **pp");
        assert_eq!(CType::Array(Box::new(CType::Scalar("uint8_t")), 16).declare("bytes"), "uint8_t bytes[16]");
        assert_eq!(CType::Pointer(Box::new(CType::Struct("Point".into()))).spelling(), "struct Point *");
        assert_eq!(CType::Scalar("double").declare("x"), "double x");
    }

    #[test]
    fn identifiers_exclude_c_words() {
        assert!(is_c_identifier("add_one"));
        assert!(is_c_identifier("_x1"));
        assert!(!is_c_identifier("int"));
        assert!(!is_c_identifier("1x"));
        assert!(!is_c_identifier("a-b"));
        assert!(!is_c_identifier(""));
        assert_eq!(guard_for("my-lib"), "BURDIN_MY_LIB_H");
    }

    #[test]
    fn a_header_has_guards_cplusplus_wrapping_structs_and_prototypes() {
        let header = ExportHeader {
            guard: "BURDIN_LIB_H".into(),
            constants: vec![ExportConstant { name: "LIB_VERSION".into(), value: "3".into() }],
            structs: vec![point()],
            functions: vec![
                ExportFunction { name: "tick".into(), ret: CType::Void, params: Vec::new() },
                ExportFunction {
                    name: "dist".into(),
                    ret: CType::Scalar("double"),
                    params: vec![("a".into(), CType::Pointer(Box::new(CType::Struct("Point".into()))))],
                },
            ],
        };
        let text = header.render();
        assert!(text.contains("#ifndef BURDIN_LIB_H\n#define BURDIN_LIB_H\n"), "{text}");
        assert!(text.contains("#ifdef __cplusplus\nextern \"C\" {\n#endif\n"), "{text}");
        assert!(text.contains("#define LIB_VERSION 3\n"), "{text}");
        assert!(
            text.contains("struct Point {\n    int32_t x;\n    int32_t y;\n};\ntypedef struct Point Point;\n"),
            "{text}"
        );
        assert!(text.contains("void tick(void);\n"), "{text}");
        assert!(text.contains("double dist(struct Point *a);\n"), "{text}");
        assert!(text.trim_end().ends_with("#endif /* BURDIN_LIB_H */"), "{text}");
    }

    #[test]
    fn a_struct_held_by_value_comes_first() {
        let line = ExportStruct {
            name: "Line".into(),
            fields: vec![("from".into(), CType::Struct("Point".into())), ("to".into(), CType::Struct("Point".into()))],
            opaque: false,
        };
        let header = ExportHeader { guard: "G".into(), structs: vec![line, point()], ..ExportHeader::default() };
        let text = header.render();
        let point_at = text.find("struct Point {").expect("Point is defined");
        let line_at = text.find("struct Line {").expect("Line is defined");
        assert!(point_at < line_at, "{text}");
    }

    #[test]
    fn an_opaque_struct_is_only_declared() {
        let header = ExportHeader {
            guard: "G".into(),
            structs: vec![ExportStruct { name: "Handle".into(), fields: Vec::new(), opaque: true }],
            ..ExportHeader::default()
        };
        let text = header.render();
        assert!(text.contains("struct Handle;\ntypedef struct Handle Handle;\n"), "{text}");
    }
}
