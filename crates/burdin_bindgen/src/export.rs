//! Writes a C header for what a Burdin package exports (`spec/bindgen.md`, BG10).
//!
//! The driver reads the checked program and builds an [`ExportHeader`]; this module only prints it. It knows C's
//! spelling of each type, the order structs must appear in, the include guard, and the `extern "C"` wrapper for C++.

/// A C type as the header spells it.
#[derive(Clone, Debug, PartialEq)]
pub enum CType {
    Void,
    /// An arithmetic type: `int32_t`, `size_t`, `double`, `bool`, ...
    Scalar(&'static str),
    Pointer(Box<CType>),
    /// A struct the header declares, by name.
    Struct(String),
    Array(Box<CType>, u64),
}

impl CType {
    /// The type as the specifier before a declarator name; an array is declared with its length after the name, so
    /// `declare` is the one to use for a field or parameter.
    pub fn spelling(&self) -> String {
        match self {
            CType::Void => "void".to_string(),
            CType::Scalar(name) => (*name).to_string(),
            CType::Pointer(inner) => match inner.as_ref() {
                CType::Pointer(_) => format!("{}*", inner.spelling()),
                other => format!("{} *", other.spelling()),
            },
            CType::Struct(name) => format!("struct {name}"),
            CType::Array(element, len) => format!("{}[{len}]", element.spelling()),
        }
    }

    /// `type name` for a field or a parameter.
    pub fn declare(&self, name: &str) -> String {
        match self {
            CType::Array(element, len) => format!("{} {name}[{len}]", element.spelling()),
            CType::Pointer(inner) if matches!(inner.as_ref(), CType::Pointer(_)) => {
                format!("{}{name}", self.spelling())
            }
            CType::Pointer(_) => format!("{}{name}", self.spelling()),
            _ => format!("{} {name}", self.spelling()),
        }
    }
}

#[derive(Clone, Debug)]
pub struct ExportStruct {
    pub name: String,
    pub fields: Vec<(String, CType)>,
    /// A struct whose layout C cannot see (it is not `repr(C)`): declared, never defined, and only used through
    /// pointers.
    pub opaque: bool,
}

#[derive(Clone, Debug)]
pub struct ExportFunction {
    pub name: String,
    pub ret: CType,
    pub params: Vec<(String, CType)>,
}

#[derive(Clone, Debug)]
pub struct ExportConstant {
    pub name: String,
    /// The text after `#define NAME`.
    pub value: String,
}

#[derive(Clone, Debug, Default)]
pub struct ExportHeader {
    /// The include guard.
    pub guard: String,
    pub constants: Vec<ExportConstant>,
    pub structs: Vec<ExportStruct>,
    pub functions: Vec<ExportFunction>,
}

/// The reserved words of C (through C23) and the few names C++ reserves that a header must not define.
