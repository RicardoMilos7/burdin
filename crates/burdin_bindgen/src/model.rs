//! What the generator knows about a header, and how it is written as a Burdin module (`spec/bindgen.md`, BG2-BG8).
//!
//! `parse.rs` fills a [`Module`] from libclang; [`Module::render`] turns it into text. Nothing here talks to libclang,
//! so the output format has plain unit tests.

/// A C type as Burdin spells it.
#[derive(Clone, Debug, PartialEq)]
pub enum Ty {
    /// `void`: a return type with nothing to say, or the pointee of `CPtr<CVoid>`.
    Void,
    /// A primitive: `i32`, `u8`, `f64`, `usize`, `CChar`, ...
    Prim(&'static str),
    /// A struct, union, enumeration, or typedef the module declares.
    Named(String),
    Ptr(Box<Ty>),
    /// A C function pointer. Burdin has no function-pointer type across the C ABI, so it is a `CPtr<CVoid>` (BG6).
    FnPtr,
    Array(Box<Ty>, u64),
}

impl Ty {
    /// The Burdin type expression.
    pub fn burdin(&self) -> String {
        match self {
            Ty::Void => "CVoid".to_string(),
            Ty::Prim(name) => (*name).to_string(),
            Ty::Named(name) => name.clone(),
            Ty::Ptr(inner) => format!("CPtr<{}>", inner.burdin()),
            Ty::FnPtr => "CPtr<CVoid>".to_string(),
            Ty::Array(element, len) => format!("[{}; {len}]", element.burdin()),
        }
    }
}

#[derive(Clone, Debug)]
pub struct Param {
    pub name: String,
    pub ty: Ty,
}

#[derive(Clone, Debug)]
pub struct Function {
    /// The symbol and the Burdin name.
    pub name: String,
    pub ret: Ty,
    pub params: Vec<Param>,
    pub variadic: bool,
    /// For a generated wrapper, the C function it calls.
    pub wrapper_of: Option<String>,
}

/// How a struct or union reaches Burdin.
#[derive(Clone, Debug, PartialEq)]
pub enum Layout {
    /// A `repr(C)` struct with the same fields: Burdin's layout equals C's.
    Natural,
    /// A struct of words with C's size and alignment, for a union or a struct whose layout Burdin cannot spell.
    /// `reason` says why when it is not a union.
    Bytes { reason: Option<String> },
    /// A declaration with no fields: an incomplete type, or one whose layout cannot be reproduced.
    Opaque { reason: Option<String> },
}

#[derive(Clone, Debug)]
pub struct Field {
    pub name: String,
    pub ty: Ty,
}

#[derive(Clone, Debug)]
pub struct Record {
    pub name: String,
    pub is_union: bool,
    pub fields: Vec<Field>,
    /// `name: type at offset` for every member, shown in a comment when the fields are not declared.
    pub members: Vec<String>,
    pub size: u64,
    pub align: u64,
    pub layout: Layout,
}

#[derive(Clone, Debug)]
pub enum Item {
    Const { name: String, ty: String, value: String },
    Alias { name: String, ty: Ty, note: Option<String> },
    Record(Record),
}

/// One header's declarations, in the order they were found.
#[derive(Default)]
pub struct Module {
    pub header: String,
    pub items: Vec<Item>,
    pub functions: Vec<Function>,
    /// Declarations that were skipped or changed, and why.
    pub notes: Vec<String>,
}

/// The word of the C unit of the given alignment that makes a blob of the right alignment: `u8` ... `u64`. `None`
/// for an alignment Burdin has no integer for.
pub fn word_for_alignment(align: u64) -> Option<&'static str> {
    match align {
        1 => Some("u8"),
        2 => Some("u16"),
        4 => Some("u32"),
        8 => Some("u64"),
        _ => None,
    }
}

impl Module {
    pub fn render(&self) -> String {
        let mut text = format!("// Generated by `burdin bindgen` from `{}`; do not edit.\n", self.header);
        for note in &self.notes {
            text.push_str(&format!("// bindgen: {note}\n"));
        }
        if !self.notes.is_empty() {
            text.push('\n');
        }
        for item in &self.items {
            match item {
                Item::Const { name, ty, value } => text.push_str(&format!("const {name}: {ty} = {value}\n")),
                Item::Alias { name, ty, note } => {
                    if let Some(note) = note {
                        text.push_str(&format!("// {note}\n"));
                    }
                    text.push_str(&format!("type {name} = {}\n", ty.burdin()));
                }
                Item::Record(record) => render_record(record, &mut text),
            }
        }
        if !self.functions.is_empty() {
            text.push_str("extern \"C\" {\n");
            for function in &self.functions {
                if let Some(original) = &function.wrapper_of {
                    text.push_str(&format!("    // a wrapper for the static inline function `{original}`\n"));
                }
                text.push_str("    ");
                text.push_str(&render_function(function));
                text.push('\n');
            }
            text.push_str("}\n");
        }
        text
    }
}

fn render_function(function: &Function) -> String {
    let mut parts: Vec<String> = function.params.iter().map(|p| format!("{}: {}", p.name, p.ty.burdin())).collect();
    if function.variadic {
        parts.push("...".to_string());
    }
    let mut text = format!("fn {}({})", function.name, parts.join(", "));
    if function.ret != Ty::Void {
        text.push_str(&format!(": {}", function.ret.burdin()));
    }
    text
}

fn render_record(record: &Record, text: &mut String) {
    let name = &record.name;
    match &record.layout {
        Layout::Natural => {
            text.push_str(&format!("struct {name} repr(C) {{\n"));
            for field in &record.fields {
                text.push_str(&format!("    {}: {}\n", field.name, field.ty.burdin()));
            }
            text.push_str("}\n");
        }
        Layout::Bytes { reason } => {
            match reason {
                None => text.push_str(&format!(
                    "// `{name}` is a C union: it is declared as words with C's size and alignment\n"
                )),
                Some(reason) => text.push_str(&format!(
                    "// `{name}` is declared as words with C's size and alignment because {reason}\n"
                )),
            }
            if !record.members.is_empty() {
                text.push_str(&format!("// members: {}\n", record.members.join(", ")));
            }
            let word = word_for_alignment(record.align).unwrap_or("u8");
            let count = record.size / record.align.max(1);
            if count == 0 {
                text.push_str(&format!("struct {name} repr(C) {{ }}\n"));
            } else {
                text.push_str(&format!("struct {name} repr(C) {{\n    bytes: [{word}; {count}]\n}}\n"));
            }
        }
        Layout::Opaque { reason } => {
            if let Some(reason) = reason {
                text.push_str(&format!("// `{name}` is declared without fields because {reason}\n"));
            }
            text.push_str(&format!("struct {name} repr(C) {{ }}\n"));
        }
    }
    if !matches!(record.layout, Layout::Opaque { .. }) {
        text.push_str(&format!(
            "comptime assert({name}.size() == {}, \"`{name}` must have size {}, as in the C header\")\n",
            record.size, record.size
        ));
        text.push_str(&format!(
            "comptime assert({name}.align() == {}, \"`{name}` must have alignment {}, as in the C header\")\n",
            record.align, record.align
        ));
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn pair() -> Record {
        Record {
            name: "Pair".into(),
            is_union: false,
            fields: vec![
                Field { name: "first".into(), ty: Ty::Prim("i32") },
                Field { name: "second".into(), ty: Ty::Prim("i32") },
            ],
            members: Vec::new(),
            size: 8,
            align: 4,
            layout: Layout::Natural,
        }
    }

    #[test]
    fn types_are_spelled_the_burdin_way() {
        let text = Ty::Ptr(Box::new(Ty::Prim("CChar"))).burdin();
        assert_eq!(text, "CPtr<CChar>");
        assert_eq!(Ty::Ptr(Box::new(Ty::Void)).burdin(), "CPtr<CVoid>");
        assert_eq!(Ty::FnPtr.burdin(), "CPtr<CVoid>");
        assert_eq!(Ty::Array(Box::new(Ty::Prim("u8")), 16).burdin(), "[u8; 16]");
        assert_eq!(Ty::Ptr(Box::new(Ty::Named("Node".into()))).burdin(), "CPtr<Node>");
    }

    #[test]
    fn a_natural_struct_is_repr_c_with_a_size_check() {
        let mut text = String::new();
        render_record(&pair(), &mut text);
        assert!(text.starts_with("struct Pair repr(C) {\n    first: i32\n    second: i32\n}\n"), "{text}");
        assert!(text.contains("comptime assert(Pair.size() == 8,"), "{text}");
        assert!(text.contains("comptime assert(Pair.align() == 4,"), "{text}");
    }

    #[test]
    fn a_union_is_words_of_its_alignment() {
        let record = Record {
            name: "Value".into(),
            is_union: true,
            fields: Vec::new(),
            members: vec!["`i`: i32".into(), "`d`: f64".into()],
            size: 8,
            align: 8,
            layout: Layout::Bytes { reason: None },
        };
        let mut text = String::new();
        render_record(&record, &mut text);
        assert!(text.contains("struct Value repr(C) {\n    bytes: [u64; 1]\n}\n"), "{text}");
        assert!(text.contains("// members: `i`: i32, `d`: f64"), "{text}");
        assert!(text.contains("Value.size() == 8"), "{text}");
    }

    #[test]
    fn an_opaque_struct_has_no_fields_and_no_check() {
        let record = Record {
            name: "Handle".into(),
            is_union: false,
            fields: Vec::new(),
            members: Vec::new(),
            size: 0,
            align: 1,
            layout: Layout::Opaque { reason: None },
        };
        let mut text = String::new();
        render_record(&record, &mut text);
        assert_eq!(text, "struct Handle repr(C) { }\n");
    }

    #[test]
    fn a_module_lists_items_then_one_extern_block() {
        let module = Module {
            header: "c/lib.h".into(),
            items: vec![
                Item::Const { name: "ANSWER".into(), ty: "i32".into(), value: "42".into() },
                Item::Alias { name: "Handle".into(), ty: Ty::Ptr(Box::new(Ty::Void)), note: None },
            ],
            functions: vec![
                Function {
                    name: "open".into(),
                    ret: Ty::Prim("i32"),
                    params: vec![Param { name: "path".into(), ty: Ty::Ptr(Box::new(Ty::Prim("CChar"))) }],
                    variadic: true,
                    wrapper_of: None,
                },
                Function { name: "close".into(), ret: Ty::Void, params: Vec::new(), variadic: false, wrapper_of: None },
            ],
            notes: vec!["`x` was skipped because it is not representable".into()],
        };
        let text = module.render();
        assert!(text.starts_with("// Generated by `burdin bindgen` from `c/lib.h`; do not edit.\n"), "{text}");
        assert!(text.contains("// bindgen: `x` was skipped because it is not representable\n"), "{text}");
        assert!(text.contains("const ANSWER: i32 = 42\ntype Handle = CPtr<CVoid>\n"), "{text}");
        assert!(
            text.contains("extern \"C\" {\n    fn open(path: CPtr<CChar>, ...): i32\n    fn close()\n}\n"),
            "{text}"
        );
    }
}
