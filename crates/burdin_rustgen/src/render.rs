//! The two outputs: the Burdin module and the shim crate's Rust source (`spec/rust-interop.md`, RI5-RI6).
//!
//! Both are printed from the same [`Api`], so the layout the module asserts and the layout the shim asserts are the
//! one this tool computed. Neither depends on the machine it ran on: the text names the crate, its version, and
//! rustdoc's format version, and nothing else.

use crate::api::{Api, Class, burdin_name, burdin_string};
use std::fmt::Write as _;

/// The Burdin module: constants, types with their layout checks, and one `extern "C"` block.
pub fn burdin_module(api: &Api, format_version: u32) -> String {
    let mut out = String::new();
    let version = api.crate_version.as_deref().map(|v| format!(" {v}")).unwrap_or_default();
    let _ = writeln!(
        out,
        "// Generated by `burdin bindgen --rust` from the `{}` crate{version} (rustdoc JSON format {format_version}); do not edit.",
        api.crate_name
    );
    for note in &api.notes {
        let _ = writeln!(out, "// bindgen: {note}");
    }
    out.push('\n');
    for constant in &api.consts {
        let _ = writeln!(out, "const {}: {} = {}", constant.name, constant.burdin_ty, constant.value);
    }
    for def in &api.types {
        match &def.class {
            Class::Enum { int, variants, constants } => {
                let _ = writeln!(out, "type {} = {}", def.name, int.name());
                for ((_, value), name) in variants.iter().zip(constants) {
                    if !name.is_empty() {
                        let _ = writeln!(out, "const {name}: {} = {value}", int.name());
                    }
                }
            }
            Class::Value { fields, size, align } => {
                let _ = writeln!(out, "struct {} repr(C) {{", def.name);
                for field in fields {
                    let _ = writeln!(out, "    {}: {}", burdin_name(&field.rust_name), field.burdin_ty);
                }
                out.push_str("}\n");
                let _ = writeln!(
                    out,
                    "comptime assert({0}.size() == {1}, {2})",
                    def.name,
                    size,
                    burdin_string(&format!("`{}` must have size {size}, as in the Rust crate", def.name))
                );
                let _ = writeln!(
                    out,
                    "comptime assert({0}.align() == {1}, {2})",
                    def.name,
                    align,
                    burdin_string(&format!("`{}` must have alignment {align}, as in the Rust crate", def.name))
                );
            }
            Class::Handle => {
                let _ = writeln!(out, "struct {} repr(C) {{ }}", def.name);
            }
        }
    }
    let has_functions = !api.wrappers.is_empty() || !api.direct.is_empty() || api.string_free.is_some();
    if has_functions {
        out.push_str("extern \"C\" {\n");
        for wrapper in &api.wrappers {
            let params = join_params(&wrapper.burdin_params);
            let _ = writeln!(out, "    fn {}({params}){}", wrapper.symbol, ret(&wrapper.burdin_ret));
        }
        for direct in &api.direct {
            let _ = writeln!(out, "    fn {}({}){}", direct.symbol, join_params(&direct.params), ret(&direct.ret));
        }
        if let Some(name) = &api.string_free {
            let _ = writeln!(out, "    fn {name}(text: CPtr<CChar>)");
        }
        out.push_str("}\n");
    }
    out
}

fn join_params(params: &[(String, String)]) -> String {
    params.iter().map(|(name, ty)| format!("{name}: {ty}")).collect::<Vec<_>>().join(", ")
}

fn ret(ty: &Option<String>) -> String {
    ty.as_ref().map(|ty| format!(": {ty}")).unwrap_or_default()
}

/// The shim crate's `src/lib.rs`: the layout checks, then one `extern "C"` function per wrapper.
pub fn shim_source(api: &Api) -> String {
    let mut out = String::new();
    let version = api.crate_version.as_deref().map(|v| format!(" {v}")).unwrap_or_default();
    let _ = writeln!(
        out,
        "// Generated by `burdin bindgen --rust` from the `{}` crate{version}; do not edit.",
        api.crate_name
    );
    out.push_str(
        "//\n\
         // Every function is exported with the C ABI. A Rust panic in one of them aborts the process, because a panic\n\
         // must not unwind into a caller that is not Rust.\n\
         #![allow(unused_unsafe, improper_ctypes_definitions, clippy::missing_safety_doc, clippy::not_unsafe_ptr_arg_deref)]\n\n",
    );
    let mut checks = String::new();
    for def in &api.types {
        let path = &def.rust_path;
        match &def.class {
            Class::Value { fields, size, align } => {
                let _ = writeln!(
                    checks,
                    "    assert!(::core::mem::size_of::<{path}>() == {size}, {});",
                    rust_string(&format!("`{}` must have size {size}", def.name))
                );
                let _ = writeln!(
                    checks,
                    "    assert!(::core::mem::align_of::<{path}>() == {align}, {});",
                    rust_string(&format!("`{}` must have alignment {align}", def.name))
                );
                for field in fields {
                    let _ = writeln!(
                        checks,
                        "    assert!(::core::mem::offset_of!({path}, {}) == {}, {});",
                        field.rust_name,
                        field.offset,
                        rust_string(&format!("`{}.{}` must be at offset {}", def.name, field.rust_name, field.offset))
                    );
                }
            }
            Class::Enum { int, .. } => {
                let _ = writeln!(
                    checks,
                    "    assert!(::core::mem::size_of::<{path}>() == ::core::mem::size_of::<{}>(), {});",
                    int.name(),
                    rust_string(&format!("`{}` must be as wide as `{}`", def.name, int.name()))
                );
            }
            Class::Handle => {}
        }
    }
    if !checks.is_empty() {
        out.push_str(
            "// The layouts `burdin bindgen` computed are the layouts rustc chose; a mismatch stops the build here\n\
             // instead of becoming a wrong read in Burdin.\n",
        );
        out.push_str("const _: () = {\n");
        out.push_str(&checks);
        out.push_str("};\n\n");
    }
    for wrapper in &api.wrappers {
        out.push_str("#[unsafe(no_mangle)]\n");
        let params = wrapper.shim_params.iter().map(|(n, t)| format!("{n}: {t}")).collect::<Vec<_>>().join(", ");
        let _ = writeln!(out, "pub extern \"C\" fn {}({params}){} {{", wrapper.symbol, ret_rust(&wrapper.shim_ret));
        for line in &wrapper.body {
            let _ = writeln!(out, "    {line}");
        }
        out.push_str("}\n\n");
    }
    if let Some(name) = &api.string_free {
        let _ = writeln!(
            out,
            "/// Frees a string a shim function returned.\n\
             #[unsafe(no_mangle)]\n\
             pub extern \"C\" fn {name}(text: *mut ::core::ffi::c_char) {{\n    \
                 if !text.is_null() {{\n        \
                     drop(unsafe {{ ::std::ffi::CString::from_raw(text) }});\n    \
                 }}\n\
             }}"
        );
    }
    while out.ends_with("\n\n") {
        out.pop();
    }
    out
}

fn ret_rust(ty: &Option<String>) -> String {
    ty.as_ref().map(|ty| format!(" -> {ty}")).unwrap_or_default()
}

/// A Rust string literal.
fn rust_string(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The shim crate's `Cargo.toml`: a static library that depends on the crate by path.
pub fn shim_manifest(shim_package: &str, library: &str, package: &str, path: &str) -> String {
    let rename = if package == library { String::new() } else { format!(", package = {}", toml_string(package)) };
    format!(
        "# Generated by `burdin bindgen --rust`; do not edit.\n\
         [package]\n\
         name = {}\n\
         version = \"0.1.0\"\n\
         edition = \"2024\"\n\
         publish = false\n\n\
         [lib]\n\
         crate-type = [\"staticlib\"]\n\n\
         [dependencies]\n\
         {} = {{ path = {}{rename} }}\n\n\
         # The shim is its own workspace, so a workspace around the crate does not adopt it.\n\
         [workspace]\n",
        toml_string(shim_package),
        library,
        toml_string(path),
    )
}

/// The shim crate's `rust-toolchain.toml`: the pinned version, for a `cargo` run by hand.
pub fn shim_toolchain(version: &str) -> String {
    format!(
        "# Generated by `burdin bindgen --rust`; do not edit.\n[toolchain]\nchannel = {}\nprofile = \"minimal\"\n",
        toml_string(version)
    )
}

fn toml_string(text: &str) -> String {
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}
