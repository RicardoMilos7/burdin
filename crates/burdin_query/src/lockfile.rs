//! `burdin.lock`: the exact packages a build used (`spec/packages.md`, PKG5-PKG8).
//!
//! The lockfile sits beside the entry package's `burdin.toml`. It lists every package of the dependency graph, the
//! entry package included, sorted by name. A path package records its name, version, and dependencies; a git
//! package also records its repository, the reference the manifest asked for, the exact commit it resolved to, and
//! the SHA-256 checksum of its files; an official package records `source = "official"` and the checksum. The format is a small TOML subset that this module both writes and reads, so a
//! lockfile is always rendered the same way and comparing two of them is comparing text.
//!
//! The package loader reads the lockfile to find where a git dependency is checked out; resolving and fetching is
//! `burdin_pkg`'s job.

use std::path::{Path, PathBuf};

/// The file name, beside `burdin.toml`.
pub const FILE_NAME: &str = "burdin.lock";

/// The format version this compiler writes and reads.
pub const FORMAT_VERSION: u32 = 1;

/// Which commit of a repository a git dependency asks for.
#[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum GitRef {
    /// The repository's default branch (its `HEAD`).
    DefaultBranch,
    Branch(String),
    Tag(String),
    /// A commit, full or abbreviated.
    Rev(String),
}

impl GitRef {
    /// The manifest key and value, or `None` for the default branch.
    pub fn key_value(&self) -> Option<(&'static str, &str)> {
        match self {
            GitRef::DefaultBranch => None,
            GitRef::Branch(b) => Some(("branch", b)),
            GitRef::Tag(t) => Some(("tag", t)),
            GitRef::Rev(r) => Some(("rev", r)),
        }
    }

    /// How a message names the reference: `the default branch`, `branch main`, `tag v1`, `rev 1a2b`.
    pub fn describe(&self) -> String {
        match self.key_value() {
            None => "the default branch".to_string(),
            Some((key, value)) => format!("{key} {value}"),
        }
    }
}

/// A git package's origin: the repository, the reference asked for, and the commit it resolved to.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GitSource {
    pub url: String,
    pub reference: GitRef,
    /// The full 40-digit commit id.
    pub commit: String,
}

/// One package of the graph.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LockedPackage {
    pub name: String,
    /// The `[package] version` of the package's manifest, when it has one.
    pub version: Option<String>,
    /// `None` for a path package (the entry package included).
    pub git: Option<GitSource>,
    /// An official package, bundled with the compiler (`spec/packages.md`, PKG15, PKG17).
    pub official: bool,
    /// `sha256:<hex>` of a git or an official package's files; `None` for a path package.
    pub checksum: Option<String>,
    /// The package names (not the `use` names) of its direct dependencies, sorted.
    pub dependencies: Vec<String>,
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Lockfile {
    /// Sorted by name; names are unique in a graph.
    pub packages: Vec<LockedPackage>,
}

impl Lockfile {
    pub fn package(&self, name: &str) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.name == name)
    }

    /// The locked package that a git dependency on `url` at `reference` resolved to.
    pub fn git_package(&self, url: &str, reference: &GitRef) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.git.as_ref().is_some_and(|g| g.url == url && &g.reference == reference))
    }

    /// The text of the file: a header comment, the format version, and one `[[package]]` table per package.
    pub fn render(&self) -> String {
        let mut out = String::new();
        out.push_str("# burdin.lock: the exact packages this package builds with. It is generated by burdin;\n");
        out.push_str("# do not edit it by hand.\n");
        out.push_str(&format!("version = {FORMAT_VERSION}\n"));
        for package in &self.packages {
            out.push_str("\n[[package]]\n");
            out.push_str(&format!("name = {}\n", quote(&package.name)));
            if let Some(version) = &package.version {
                out.push_str(&format!("version = {}\n", quote(version)));
            }
            if package.official {
                out.push_str("source = \"official\"\n");
            }
            if let Some(git) = &package.git {
                out.push_str(&format!("git = {}\n", quote(&git.url)));
                if let Some((key, value)) = git.reference.key_value() {
                    out.push_str(&format!("{key} = {}\n", quote(value)));
                }
                out.push_str(&format!("commit = {}\n", quote(&git.commit)));
            }
            if let Some(checksum) = &package.checksum {
                out.push_str(&format!("checksum = {}\n", quote(checksum)));
            }
            let deps: Vec<String> = package.dependencies.iter().map(|d| quote(d)).collect();
            out.push_str(&format!("dependencies = [{}]\n", deps.join(", ")));
        }
        out
    }
}

/// Reads `burdin.lock` in `dir`. `Ok(None)` when there is none.
pub fn read(dir: &Path) -> Result<Option<Lockfile>, String> {
    let path = dir.join(FILE_NAME);
    match std::fs::read_to_string(&path) {
        Ok(text) => parse(&text).map(Some).map_err(|e| format!("{}: {e}", crate::package::source_path_text(&path))),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(format!("cannot read {}: {e}", crate::package::source_path_text(&path))),
    }
}

/// Parses a lockfile. Errors name the line (`3: ...`).
pub fn parse(text: &str) -> Result<Lockfile, String> {
    let mut packages: Vec<LockedPackage> = Vec::new();
    // The fields of the table being read: (key, value, line).
    let mut table: Option<Vec<(String, String, usize)>> = None;
    let mut version: Option<u32> = None;
    for (index, raw) in text.lines().enumerate() {
        let line_number = index + 1;
        let line = crate::package::strip_comment(raw).trim();
        if line.is_empty() {
            continue;
        }
        if line == "[[package]]" {
            if let Some(fields) = table.take() {
                packages.push(package_from(fields)?);
            }
            table = Some(Vec::new());
            continue;
        }
        if line.starts_with('[') {
            return Err(format!("{line_number}: unexpected table `{line}`; a lockfile has only `[[package]]` tables"));
        }
        let Some((key, value)) = line.split_once('=') else {
            return Err(format!("{line_number}: expected `key = value`"));
        };
        let (key, value) = (key.trim().to_string(), value.trim().to_string());
        match &mut table {
            Some(fields) => {
                if fields.iter().any(|(k, _, _)| *k == key) {
                    return Err(format!("{line_number}: `{key}` is given twice in one package"));
                }
                fields.push((key, value, line_number));
            }
            None if key == "version" => {
                let number: u32 =
                    value.parse().map_err(|_| format!("{line_number}: the format `version` must be a number"))?;
                if number != FORMAT_VERSION {
                    return Err(format!(
                        "{line_number}: lockfile format version {number} is not supported (this burdin reads \
                         version {FORMAT_VERSION})"
                    ));
                }
                version = Some(number);
            }
            None => {}
        }
    }
    if let Some(fields) = table.take() {
        packages.push(package_from(fields)?);
    }
    if version.is_none() {
        return Err("the lockfile has no format `version`".to_string());
    }
    packages.sort_by(|a, b| a.name.cmp(&b.name));
    for pair in packages.windows(2) {
        if pair[0].name == pair[1].name {
            return Err(format!("package `{}` is listed twice", pair[0].name));
        }
    }
    Ok(Lockfile { packages })
}

fn package_from(fields: Vec<(String, String, usize)>) -> Result<LockedPackage, String> {
    let mut name = None;
    let mut version = None;
    let mut url = None;
    let mut reference = GitRef::DefaultBranch;
    let mut commit = None;
    let mut official = false;
    let mut checksum = None;
    let mut dependencies = Vec::new();
    let mut first_line = usize::MAX;
    for (key, value, line) in fields {
        first_line = first_line.min(line);
        let string = || crate::package::parse_string(&value).map_err(|e| format!("{line}: {e}"));
        match key.as_str() {
            "name" => name = Some(string()?),
            "version" => version = Some(string()?),
            "git" => url = Some(string()?),
            "branch" => reference = GitRef::Branch(string()?),
            "tag" => reference = GitRef::Tag(string()?),
            "rev" => reference = GitRef::Rev(string()?),
            "commit" => commit = Some(string()?),
            "source" => match string()?.as_str() {
                "official" => official = true,
                other => return Err(format!("{line}: package source `{other}` is not supported by this burdin")),
            },
            "checksum" => checksum = Some(string()?),
            "dependencies" => {
                dependencies = crate::package::parse_string_array(&value).map_err(|e| format!("{line}: {e}"))?;
                dependencies.sort();
            }
            // A newer burdin may record more; this one ignores what it does not know.
            _ => {}
        }
    }
    let Some(name) = name else {
        return Err(format!("{first_line}: a `[[package]]` table needs a `name`"));
    };
    let git = match (url, commit) {
        (Some(url), Some(commit)) => Some(GitSource { url, reference, commit }),
        (None, None) => None,
        _ => return Err(format!("package `{name}`: a git package needs both `git` and `commit`")),
    };
    if official && git.is_some() {
        return Err(format!("package `{name}`: a package is official or from git, not both"));
    }
    Ok(LockedPackage { name, version, git, official, checksum, dependencies })
}

/// A TOML basic string with the escapes `parse_string` reads.
pub fn quote(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The directory name for one repository in the git cache: the repository's last path segment (for people reading
/// the cache) and a hash of the whole URL (so two repositories never share a directory).
pub fn git_cache_key(url: &str) -> String {
    let trimmed = url.trim_end_matches('/');
    let last = trimmed.rsplit(['/', '\\', ':']).next().unwrap_or("");
    let last = last.strip_suffix(".git").unwrap_or(last);
    let readable: String =
        last.chars().filter(|c| c.is_ascii_alphanumeric() || *c == '_' || *c == '-').take(32).collect();
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in url.as_bytes() {
        hash = (hash ^ u64::from(*byte)).wrapping_mul(0x0000_0100_0000_01b3);
    }
    if readable.is_empty() { format!("{hash:016x}") } else { format!("{readable}-{hash:016x}") }
}

/// The git cache under the Burdin home: `<home>/git`.
pub fn git_cache_dir() -> Result<PathBuf, String> {
    crate::package::home_dir()
        .map(|home| home.join("git"))
        .ok_or_else(|| "cannot find the Burdin home directory for the git cache: set BURDIN_HOME".to_string())
}

/// Where the files of `url` at `commit` are checked out: `<home>/git/checkouts/<key>/<commit>`.
pub fn git_checkout_dir(url: &str, commit: &str) -> Result<PathBuf, String> {
    Ok(git_cache_dir()?.join("checkouts").join(git_cache_key(url)).join(commit))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> Lockfile {
        Lockfile {
            packages: vec![
                LockedPackage {
                    name: "app".into(),
                    version: Some("0.1.0".into()),
                    git: None,
                    official: false,
                    checksum: None,
                    dependencies: vec!["json".into(), "util".into(), "yaml".into()],
                },
                LockedPackage {
                    name: "json".into(),
                    version: Some("1.2.0".into()),
                    git: Some(GitSource {
                        url: "https://example.com/json.git".into(),
                        reference: GitRef::Tag("v1.2.0".into()),
                        commit: "0123456789abcdef0123456789abcdef01234567".into(),
                    }),
                    official: false,
                    checksum: Some("sha256:00ff".into()),
                    dependencies: vec![],
                },
                LockedPackage {
                    name: "util".into(),
                    version: None,
                    git: None,
                    official: false,
                    checksum: None,
                    dependencies: vec![],
                },
                LockedPackage {
                    name: "yaml".into(),
                    version: Some("0.1.0".into()),
                    git: None,
                    official: true,
                    checksum: Some("sha256:ab12".into()),
                    dependencies: vec![],
                },
            ],
        }
    }

    #[test]
    fn render_is_the_documented_text() {
        let expected = "# burdin.lock: the exact packages this package builds with. It is generated by burdin;
# do not edit it by hand.
version = 1

[[package]]
name = \"app\"
version = \"0.1.0\"
dependencies = [\"json\", \"util\", \"yaml\"]

[[package]]
name = \"json\"
version = \"1.2.0\"
git = \"https://example.com/json.git\"
tag = \"v1.2.0\"
commit = \"0123456789abcdef0123456789abcdef01234567\"
checksum = \"sha256:00ff\"
dependencies = []

[[package]]
name = \"util\"
dependencies = []

[[package]]
name = \"yaml\"
version = \"0.1.0\"
source = \"official\"
checksum = \"sha256:ab12\"
dependencies = []
";
        assert_eq!(sample().render(), expected);
    }

    #[test]
    fn parse_reads_what_render_writes() {
        let lock = sample();
        assert_eq!(parse(&lock.render()).unwrap(), lock);
    }

    #[test]
    fn lookups_by_name_and_by_git_source() {
        let lock = sample();
        assert_eq!(lock.package("util").map(|p| p.dependencies.len()), Some(0));
        let found = lock.git_package("https://example.com/json.git", &GitRef::Tag("v1.2.0".into()));
        assert_eq!(found.map(|p| p.name.as_str()), Some("json"));
        assert!(lock.git_package("https://example.com/json.git", &GitRef::DefaultBranch).is_none());
    }

    #[test]
    fn malformed_lockfiles_are_rejected_with_a_line() {
        assert!(parse("[[package]]\nname = \"a\"\n").unwrap_err().contains("no format `version`"));
        assert!(parse("version = 2\n").unwrap_err().contains("version 2 is not supported"));
        assert!(parse("version = 1\n[package]\n").unwrap_err().starts_with("2:"));
        assert!(parse("version = 1\n[[package]]\nversion = \"1\"\n").unwrap_err().contains("needs a `name`"));
        assert!(parse("version = 1\n[[package]]\nname = \"a\"\ngit = \"x\"\n").unwrap_err().contains("`commit`"));
        let twice = "version = 1\n[[package]]\nname = \"a\"\n[[package]]\nname = \"a\"\n";
        assert!(parse(twice).unwrap_err().contains("listed twice"));
        assert!(parse("version = 1\n[[package]]\nname = a\n").unwrap_err().starts_with("3:"));
        let registry = "version = 1\n[[package]]\nname = \"a\"\nsource = \"registry\"\n";
        assert!(parse(registry).unwrap_err().starts_with("4: package source `registry`"));
        let both = "version = 1\n[[package]]\nname = \"a\"\nsource = \"official\"\ngit = \"x\"\ncommit = \"c\"\n";
        assert!(parse(both).unwrap_err().contains("not both"));
    }

    #[test]
    fn unknown_keys_are_ignored() {
        let lock = parse("version = 1\nfuture = true\n[[package]]\nname = \"a\"\nextra = 3\n").unwrap();
        assert_eq!(lock.packages.len(), 1);
    }

    #[test]
    fn cache_keys_are_readable_and_distinct() {
        let a = git_cache_key("https://example.com/org/json.git");
        let b = git_cache_key("https://example.org/org/json.git");
        assert!(a.starts_with("json-"), "{a}");
        assert_ne!(a, b);
        assert_eq!(a, git_cache_key("https://example.com/org/json.git"));
        assert!(git_cache_key("C:\\repos\\my lib").starts_with("mylib-"));
    }
}
