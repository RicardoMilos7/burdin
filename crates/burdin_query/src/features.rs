//! Features (`spec/packages.md`, PKG22-PKG26): the items a `[features]` table and a dependency's `features` list name,
//! the `--features` list of the command line, and the text of the generated `features` module. The fixed point that
//! decides which features a build enables loads packages, so it lives with the loader (`package.rs`, `Loader::activate`).

use burdin_syntax::token::TokenKind;

/// One item of a feature list (PKG22).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Item<'a> {
    /// A feature of the package, or the name of an optional dependency (an implicit feature).
    Name(&'a str),
    /// `dep:x`: enables the optional dependency `x`.
    Dep(&'a str),
    /// `x/feature`: enables `feature` in the dependency `x`, and enables `x` when it is optional.
    Forward { dep: &'a str, feature: &'a str },
}

/// The meaning of one item of a feature list. It does not check that the names exist: the manifest parser and the
/// activation do that, each with the context its error needs.
pub fn parse_item(text: &str) -> Item<'_> {
    if let Some(dep) = text.strip_prefix("dep:") {
        Item::Dep(dep)
    } else if let Some((dep, feature)) = text.split_once('/') {
        Item::Forward { dep, feature }
    } else {
        Item::Name(text)
    }
}

/// Whether `name` can name a feature: a Burdin identifier that is not a keyword, because the feature becomes a
/// constant of the `features` module (PKG22, PKG26).
pub fn is_feature_name(name: &str) -> bool {
    crate::package::is_ident(name) && TokenKind::keyword(name).is_none()
}

/// The names of a `--features` list: separated by commas or spaces (PKG23). Empty pieces are dropped.
pub fn split_request(text: &str) -> Vec<String> {
    text.split(|c: char| c == ',' || c.is_whitespace()).filter(|piece| !piece.is_empty()).map(str::to_string).collect()
}

/// The source text of the generated `features` module: one `const` per entry, sorted by name, each `true` when the
/// build enables the feature (PKG26). Entries are `(name, enabled)`; a name appears once. A module's own declarations
/// are public unless marked `priv`, and `pub` is written only before `use` (spec/grammar.md), so the constants carry
/// no visibility word.
pub fn module_text(entries: &[(String, bool)]) -> String {
    let mut sorted: Vec<&(String, bool)> = entries.iter().collect();
    sorted.sort_by(|a, b| a.0.cmp(&b.0));
    sorted.dedup_by(|a, b| a.0 == b.0);
    let mut text = String::from(
        "// Generated by burdin from the features of burdin.toml (spec/packages.md, PKG26). Do not edit: the build\n\
         // writes this module in memory, so each build sees the features it enables.\n",
    );
    for (name, enabled) in sorted {
        text.push_str(&format!("const {name}: bool = {enabled}\n"));
    }
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn items_are_names_deps_or_forwards() {
        assert_eq!(parse_item("fast"), Item::Name("fast"));
        assert_eq!(parse_item("dep:json"), Item::Dep("json"));
        assert_eq!(parse_item("json/pretty"), Item::Forward { dep: "json", feature: "pretty" });
    }

    #[test]
    fn feature_names_are_identifiers_that_are_not_keywords() {
        for ok in ["fast", "default", "Json2", "_x"] {
            assert!(is_feature_name(ok), "{ok}");
        }
        for bad in ["", "2x", "a-b", "type", "true", "dep:x"] {
            assert!(!is_feature_name(bad), "{bad}");
        }
    }

    #[test]
    fn request_lists_split_on_commas_and_spaces() {
        assert_eq!(split_request("a,b c,,\td"), vec!["a", "b", "c", "d"]);
        assert!(split_request(" , ").is_empty());
    }

    #[test]
    fn the_module_lists_constants_sorted_and_once() {
        let text = module_text(&[("json".into(), true), ("default".into(), false), ("fast".into(), true)]);
        assert!(text.ends_with("const default: bool = false\nconst fast: bool = true\nconst json: bool = true\n"));
        let twice = module_text(&[("fast".into(), true), ("fast".into(), true)]);
        assert_eq!(twice.matches("const fast").count(), 1);
    }
}
