#!/usr/bin/env python3
"""Black-box tests for `burdin bindgen` and `burdin bindgen --export` (spec/bindgen.md, BG1-BG11).

The import side is read through libclang, so these tests need a libclang the driver can load (`libclang-21-dev` on
Debian and Ubuntu, Homebrew's `llvm@21` on macOS, the LLVM release archive on Windows) and a C compiler for the parts
that build C. Both are installed in every CI job.

  * each fixture header generates the module in tests/bindgen/expected byte for byte (the goldens are compared
    everywhere but Windows: they assume a 64-bit non-MSVC C ABI. On Windows the generated module is still compiled and
    run, which is what checks its declarations);
  * the generated module compiles and its layout-check constants hold, and its constants, sizes, and alignments are the
    ones the C header gives;
  * `-I` and `-D` reach the C front end: a declaration behind `#ifdef` appears only when it is defined, and a struct
    from an included header becomes a field;
  * `--wrappers` writes C for the `static inline` functions, that C builds with the system compiler, and the calls
    return what C says when the object is linked with `--link-lib`;
  * `--export` writes the header in tests/bindgen/export/expected.h, a C and a C++ program compile against it, and on
    Linux a C shared library calls the Burdin exports through it and prints the right answers;
  * a missing header, an unknown option, `--export` without `--out`, and a header clang rejects fail with the exit
    codes the command documents (2 for usage and I/O, 1 for a header that does not parse);
  * a signature a C header cannot spell is E0263, reported for every offending declaration at once.
"""

import os
import sys
from pathlib import Path

import harness

FIXTURES = harness.TESTS / "bindgen"
HEADERS = FIXTURES / "headers"
EXPECTED = FIXTURES / "expected"

problems = []
checks = 0


def add_problem(message: str) -> None:
    problems.append(message)


def check(condition: bool, message: str) -> None:
    global checks
    checks += 1
    if not condition:
        add_problem(message)


def output(result) -> str:
    return harness.text(result.stdout) + harness.text(result.stderr)


burdin = harness.require_burdin()


def bindgen(*args, cwd=FIXTURES):
    return harness.run([burdin, "bindgen", *args], cwd=cwd)


def write_package(root: Path, modules: dict, main: str) -> None:
    source = root / "src"
    source.mkdir(parents=True)
    harness.write_text(root / "burdin.toml", '[package]\nname = "bindings"\nversion = "0.1.0"\n')
    for name, text in modules.items():
        harness.write_text(source / f"{name}.bd", text)
    harness.write_text(source / "main.bd", main)


def run_package(root: Path, *extra):
    return harness.run([burdin, "run", str(root), *extra], cwd=root)


def c_compiler():
    """An `cc`-style compiler: the one `BURDIN_CC` names, or the first of cc, clang, and gcc on `PATH`."""
    named = os.environ.get("BURDIN_CC")
    if named:
        return named
    for name in ("cc", "clang", "gcc"):
        found = harness.which(name)
        if found:
            return found
    return None


cc = c_compiler()

with harness.temporary_dir("burdin-bindgen-") as work:
    generated = work / "generated"
    generated.mkdir()

    # --- The golden modules ------------------------------------------------------------------------------------
    golden_cases = [
        ("types", "headers/types.h", []),
        ("layout", "headers/layout.h", []),
        ("macros", "headers/macros.h", []),
        ("callbacks", "headers/callbacks.h", []),
        ("outer", "headers/outer.h", ["-I", "headers/include"]),
    ]
    for name, header, extra in golden_cases:
        target = generated / f"{name}.bd"
        result = bindgen(header, "--out", str(target), *extra)
        check(result.returncode == 0, f"bindgen {header} exited {result.returncode}: {output(result).strip()}")
        if result.returncode != 0:
            continue
        check(target.is_file(), f"bindgen {header} wrote no module")
        if not target.is_file():
            continue
        actual = harness.read_text(target)
        if harness.PLATFORM == "windows":
            # The goldens assume a non-MSVC C ABI (enum underlying types and `long`), so only their shape is
            # checked here; the package below compiles and runs the module, which is the real test.
            check(actual.startswith(f"// Generated by `burdin bindgen` from `{header}`; do not edit.\n"), f"{name}.bd: wrong first line")
        else:
            expected = harness.read_text(EXPECTED / f"{name}.bd")
            check(actual == expected, f"{name}.bd does not match tests/bindgen/expected/{name}.bd")

    # --- The wrappers for `static inline` functions ------------------------------------------------------------
    inline_module = generated / "inline.bd"
    inline_wrappers = generated / "inline_wrappers.c"
    result = bindgen(
        "headers/inline.h",
        "--out",
        str(inline_module),
        "--wrappers",
        str(inline_wrappers),
        "--wrapper-include",
        "inline.h",
    )
    check(result.returncode == 0, f"bindgen headers/inline.h exited {result.returncode}: {output(result).strip()}")
    check("a variadic function cannot be wrapped" in output(result), "the variadic `static inline` function was not reported")
    if result.returncode == 0:
        check(inline_wrappers.is_file(), "bindgen wrote no wrapper file")
        if inline_wrappers.is_file():
            if harness.PLATFORM != "windows":
                check(
                    harness.read_text(inline_wrappers) == harness.read_text(EXPECTED / "inline_wrappers.c"),
                    "inline_wrappers.c does not match tests/bindgen/expected/inline_wrappers.c",
                )
            check("#include \"inline.h\"" in harness.read_text(inline_wrappers), "the wrapper file does not include the header")

    # --- The generated module compiles, and what it declares is what C says ------------------------------------
    modules = {}
    for name, _, _ in golden_cases:
        path = generated / f"{name}.bd"
        if path.is_file():
            modules[name] = harness.read_text(path)
    if inline_module.is_file():
        modules["inline"] = harness.read_text(inline_module)

    packages = {
        "types": (
            """use generated.{SHAPE_MAX, SHAPE_NAME, COLOR_GREEN, Shape, Vec2, Pair}

fn main() {
    println("{}", SHAPE_MAX)
    println("{}", SHAPE_NAME)
    println("{}", COLOR_GREEN)
    println("{} {} {} {}", Shape.size(), Shape.align(), Vec2.size(), Pair.size())
}
""",
            "16\nshape \"lib\" {v1}\n-1\n96 8 16 8\n",
            "types",
        ),
        "layout": (
            """use generated.{Number, Packed, Flags, Header, Wide, Anonymous, Plain, Holder}

fn main() {
    println("{} {} {} {}", Number.size(), Packed.size(), Flags.size(), Holder.size())
    println("{} {}", Plain.align(), Anonymous.size())
}
""",
            "16 5 4 40\n4 8\n",
            "layout",
        ),
        "macros": (
            """use generated.{COUNT_TWICE, WIDE, UNSIGNED, RATIO, GREETING, CAST, BOTH, FROM_ENUM}

fn main() {
    println("{} {} {} {:?}", COUNT_TWICE, WIDE, UNSIGNED, RATIO)
    println("{} {} {} {}", GREETING, CAST, BOTH, FROM_ENUM)
}
""",
            "20 5000000000 4000000000 1.5\nhello world 44 1 3\n",
            "macros",
        ),
        "callbacks": (
            """use generated.{Visitor, visit_fn}

fn main() {
    let callback: visit_fn = unsafe { CPtr.null() }
    let empty = unsafe { callback.is_null() }
    println("{} {}", Visitor.size(), empty)
}
""",
            "24 true\n",
            "callbacks",
        ),
        "outer": (
            """use generated.{OUTER_CONSTANT, Outer}

fn main() {
    println("{} {}", OUTER_CONSTANT, Outer.size())
}
""",
            "100 24\n",
            "outer",
        ),
        "inline": (
            """use generated.{add__extern, scale__extern, bump__extern, length__extern}

fn main() {
    println("{}", unsafe { add__extern(2, 3) })
    let mut factor: f64 = 1.5
    println("{:?}", unsafe { scale__extern(2.0, &mut factor as CPtr<f64>) })
    let mut counter: i32 = 40
    unsafe { bump__extern(&mut counter as CPtr<i32>) }
    println("{}", counter)
    let text = CString.from("hello, world")
    println("{}", unsafe { length__extern(text.as_ptr()) })
}
""",
            "5\n3.0\n41\n12\n",
            "inline",
        ),
    }

    wrappers_object = None
    if cc and inline_wrappers.is_file():
        wrappers_object = work / "inline_wrappers.o"
        compiled = harness.run(
            [cc, "-c", str(inline_wrappers), "-I", str(HEADERS), "-o", str(wrappers_object)],
        )
        check(compiled.returncode == 0, f"the system C compiler rejected the wrappers: {output(compiled).strip()}")
        if compiled.returncode != 0:
            wrappers_object = None

    for name, (main, expected_output, needed) in packages.items():
        if needed not in modules:
            continue
        if name == "inline" and wrappers_object is None:
            continue
        root = work / name
        write_package(root, {"generated": modules[needed]}, main)
        extra = ["--link-lib", str(wrappers_object)] if name == "inline" else []
        result = run_package(root, *extra)
        check(result.returncode == 0, f"the module generated from {name}.h did not compile: {output(result).strip()}")
        check(harness.text(result.stdout) == expected_output, f"{name}: printed {harness.text(result.stdout)!r}, expected {expected_output!r}")

    # --- The C front end's options -----------------------------------------------------------------------------
    default_options = work / "options.bd"
    result = bindgen("headers/options.h", "--out", str(default_options))
    check(result.returncode == 0, f"bindgen headers/options.h exited {result.returncode}: {output(result).strip()}")
    if default_options.is_file():
        text = harness.read_text(default_options)
        check("fn present(x: i32)" in text, "a declaration that is not guarded by `#ifdef` was dropped")
        check("extra_function" not in text, "a declaration behind an undefined `#ifdef` was generated")

    defined = work / "options_defined.bd"
    result = bindgen("headers/options.h", "--out", str(defined), "-D", "WITH_EXTRA", "-D", "WITHOUT_PRESENT")
    check(result.returncode == 0, f"bindgen -D exited {result.returncode}: {output(result).strip()}")
    if defined.is_file():
        text = harness.read_text(defined)
        check("fn extra_function(x: i32)" in text, "`-D` did not reach the C front end")
        check("fn present(x: i32)" not in text, "a declaration behind a defined `#else` guard was generated")

    clang_arg = work / "options_clang_arg.bd"
    result = bindgen("headers/options.h", "--out", str(clang_arg), "--clang-arg=-DWITH_EXTRA")
    check(result.returncode == 0, f"bindgen --clang-arg exited {result.returncode}: {output(result).strip()}")
    if clang_arg.is_file():
        check("fn extra_function(x: i32)" in harness.read_text(clang_arg), "`--clang-arg` did not reach the C front end")

    # --- The export header --------------------------------------------------------------------------------------
    export_dir = work / "export"
    export_dir.mkdir()
    export_header = export_dir / "exports.h"
    result = bindgen("--export", ".", "--out", str(export_header), cwd=FIXTURES / "export")
    check(result.returncode == 0, f"bindgen --export exited {result.returncode}: {output(result).strip()}")
    if export_header.is_file():
        check(
            harness.read_text(export_header) == harness.read_text(FIXTURES / "export" / "expected.h"),
            "the export header does not match tests/bindgen/export/expected.h",
        )
        header_text = harness.read_text(export_header)
        for needle in ("#ifndef BURDIN_EXPORTS_H", "#ifdef __cplusplus", "extern \"C\" {", "#define LIB_VERSION 3", "int32_t point_sum(struct Point *p);"):
            check(needle in header_text, f"the export header is missing {needle!r}")

    if cc and export_header.is_file():
        # The header is valid C and valid C++, which is what the `extern "C"` block and the typedefs are for.
        c_probe = export_dir / "probe.c"
        harness.write_text(
            c_probe,
            '#include "exports.h"\nint probe(void) { return add_one(1) + (int)LIB_VERSION; }\n',
        )
        compiled = harness.run([cc, "-fsyntax-only", "-I", str(export_dir), str(c_probe)])
        check(compiled.returncode == 0, f"the export header is not valid C: {output(compiled).strip()}")
        cpp_probe = export_dir / "probe.cpp"
        harness.write_text(
            cpp_probe,
            '#include "exports.h"\nint probe() { Point p{3, 4}; return point_sum(&p) + (int)LIB_VERSION; }\n',
        )
        compiled = harness.run([cc, "-x", "c++", "-fsyntax-only", "-I", str(export_dir), str(cpp_probe)])
        check(compiled.returncode == 0, f"the export header is not valid C++: {output(compiled).strip()}")

    # The round trip: a C library calls the Burdin exports through the header. The executable exports its symbols on
    # Linux (`-rdynamic`), which is how the library finds them.
    if cc and export_header.is_file() and harness.PLATFORM == "linux":
        library = export_dir / "libuser.so"
        compiled = harness.run(
            [cc, "-shared", "-fPIC", str(FIXTURES / "export" / "c" / "user.c"), "-I", str(export_dir), "-o", str(library)],
        )
        check(compiled.returncode == 0, f"the C side did not build against the header: {output(compiled).strip()}")
        if compiled.returncode == 0:
            program = export_dir / "exports"
            result = harness.run([burdin, "build", ".", "-o", str(program), "--link-lib", str(library)], cwd=FIXTURES / "export")
            check(result.returncode == 0, f"the exporting package did not link with the C library: {output(result).strip()}")
            if result.returncode == 0:
                environment = {**os.environ, "LD_LIBRARY_PATH": str(export_dir)}
                ran = harness.run([program], cwd=export_dir, env=environment)
                expected_output = (
                    "add_one(41) = 42\n"
                    "scale(2.0, LIB_RATIO) = 5.0\n"
                    "point_sum = 7\n"
                    "segment_dx = 9\n"
                    "fill = 7777\n"
                    "name_length = 6\n"
                    'version = 3, offset = -4, name = exports "v3"\n'
                    "big = 5000000000\n"
                    "sizes = 8 28\n"
                    "c returned 0\n"
                )
                check(ran.returncode == 0, f"the round-trip program exited {ran.returncode}: {output(ran).strip()}")
                check(
                    harness.text(ran.stdout) == expected_output,
                    f"the round trip printed {harness.text(ran.stdout)!r}, expected {expected_output!r}",
                )
    elif harness.PLATFORM != "linux":
        print("note: the C-to-Burdin round trip runs on Linux only")

    # --- Failures ----------------------------------------------------------------------------------------------
    missing = bindgen("headers/does_not_exist.h", "--out", str(work / "missing.bd"))
    check(missing.returncode == 2, f"a missing header exited {missing.returncode}, expected 2")
    check("cannot read" in output(missing), "a missing header is not reported")

    unknown = bindgen("headers/types.h", "--bogus")
    check(unknown.returncode == 2, f"an unknown option exited {unknown.returncode}, expected 2")

    no_out = bindgen("--export", ".")
    check(no_out.returncode == 2, f"`--export` without `--out` exited {no_out.returncode}, expected 2")
    check("--out" in output(no_out), "`--export` without `--out` does not say what is missing")

    broken = bindgen("headers/broken.h", "--out", str(work / "broken.bd"))
    check(broken.returncode == 1, f"a header clang rejects exited {broken.returncode}, expected 1")
    check("does_not_exist.h" in harness.text(broken.stderr), "the C error is not reported")
    check("could not parse headers/broken.h" in harness.text(broken.stderr), "the failing header is not named")

    invalid = bindgen("--export", ".", "--out", str(work / "invalid.h"), cwd=FIXTURES / "export_invalid")
    invalid_output = output(invalid)
    check(invalid.returncode == 1, f"an unexportable package exited {invalid.returncode}, expected 1")
    check(invalid_output.count("error[E0263]") == 5, f"expected five E0263 reports, saw {invalid_output.count('error[E0263]')}")
    # The reports wrap to the terminal width, so the text is compared with its whitespace collapsed.
    collapsed = " ".join(invalid_output.split())
    for needle in (
        "the constant `double` is not a name a C header can declare",
        "`int` is not a name a C header can declare",
        "cannot export `holder_value`",
        "is not `repr(C)`, so C cannot see its layout",
        "cannot export `odd_value`",
        "the field `int` of `Odd` is not a name a C header can declare",
        "cannot export `wrapped`",
        "has no C declaration",
    ):
        check(needle in collapsed, f"the E0263 report does not mention {needle!r}")
    check(not (work / "invalid.h").exists(), "a failed export still wrote a header")

    # A 128-bit integer has no C spelling, so the header cannot declare a struct that holds one (spec/int128.md, I128-13).
    wide = bindgen("--export", ".", "--out", str(work / "wide.h"), cwd=FIXTURES / "export_wide")
    wide_output = " ".join(output(wide).split())
    check(wide.returncode == 1, f"an export with a 128-bit field exited {wide.returncode}, expected 1")
    check("error[E0263]" in wide_output, "the 128-bit field was not reported as E0263")
    check(
        "the type `u128` has no C spelling" in wide_output,
        "the 128-bit field's E0263 report does not say the type has no C spelling",
    )
    check(not (work / "wide.h").exists(), "a failed export with a 128-bit field still wrote a header")

    # A C `__int128` has no Burdin equivalent: its function is skipped with a note, and the others are generated.
    wide_header = work / "wide_header.bd"
    result = bindgen("headers/wide.h", "--out", str(wide_header))
    check(result.returncode == 0, f"bindgen headers/wide.h exited {result.returncode}: {output(result).strip()}")
    if wide_header.is_file():
        text = harness.read_text(wide_header)
        check("fn small_value(x: i32)" in text, "the function beside a `__int128` one was not generated")
        check("fn wide_value(" not in text, "a function with a C `__int128` parameter was generated")
        check(
            "the type `__int128` has no Burdin equivalent" in text,
            "the skipped `__int128` function is not reported in the module",
        )

print(f"Checked `burdin bindgen` and `burdin bindgen --export` ({checks} checks)")

if harness.report_problems(problems):
    sys.exit(1)
print("No problems.")
