#!/usr/bin/env python3
"""Generates std/src/atomic.bd: the atomic types (issue #217).

Burdin has no numeric interface, so each atomic integer type is written out once, from the template here. Edit the
template and run

    python3 tests/gen_atomic_std.py

`python3 tests/gen_atomic_std.py --check` fails when std/src/atomic.bd differs from the generated text
(`tests/check_tests.py` runs it in CI).
"""

import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "std" / "src" / "atomic.bd"

# name, value type, word type, word bits
INTS = [
    ("AtomicI32", "i32", "u32", 32),
    ("AtomicU32", "u32", "u32", 32),
    ("AtomicI64", "i64", "u64", 64),
    ("AtomicU64", "u64", "u64", 64),
    ("AtomicIsize", "isize", "u64", 64),
    ("AtomicUsize", "usize", "u64", 64),
]

HEADER = """// Atomic types (spec/shared.md, SH7).
//
// GENERATED by tests/gen_atomic_std.py: edit the template there, not this file. Burdin has no numeric interface to write
// one body for every integer type, so each atomic type is written out.
//
// An atomic value lives in a small heap cell, so the handle is the same for every task that uses it and the operations
// work through a shared view (`&self`): `counter.fetch_add(1)` needs no `mut`. Every operation is sequentially
// consistent: all the atomic operations of a program happen in one order that every task agrees on. That is the
// strongest and simplest memory order; the weaker ones are not offered.
//
// The types are `Send` and `Sync` (the compiler cannot see why: the cell is behind a raw pointer). A task shares one
// by borrowing it in a scope (`task.scope`) or by putting it in a `Shared` (`Shared.new(AtomicUsize.new(0))`).

use marker.{Send, Sync}
"""

BOOL = """
/// A flag that tasks and threads can read and write without a lock.
struct AtomicBool {
    cell: CPtr<u32>
}

AtomicBool {
    /// A new flag holding `value`.
    fn new(value: bool): AtomicBool {
        unsafe {
            let cell = __alloc(4, 4) as CPtr<u32>
            __atomic_store_u32(cell, if value { 1 } else { 0 })
            AtomicBool { cell: cell }
        }
    }

    /// The current value.
    fn load(self): bool {
        unsafe {
            __atomic_load_u32(self.cell) != 0
        }
    }

    /// Writes `value`.
    fn store(self, value: bool) {
        unsafe {
            __atomic_store_u32(self.cell, if value { 1 } else { 0 })
        }
    }

    /// Writes `value` and returns the value that was there.
    fn swap(self, value: bool): bool {
        unsafe {
            __atomic_swap_u32(self.cell, if value { 1 } else { 0 }) != 0
        }
    }

    /// Writes `new` if the flag holds `current`. `Ok(old)` when it did (and `old == current`), `Err(actual)` when it held
    /// something else and was left alone.
    fn compare_exchange(self, current: bool, new: bool): Result<bool, bool> {
        unsafe {
            let c: u32 = if current { 1 } else { 0 }
            let n: u32 = if new { 1 } else { 0 }
            let old = __atomic_cas_u32(self.cell, c, n)
            if old == c {
                Ok(old != 0)
            } else {
                Err(old != 0)
            }
        }
    }

    /// Sets the flag to `old && value` and returns the old value.
    fn fetch_and(self, value: bool): bool {
        unsafe {
            __atomic_and_u32(self.cell, if value { 1 } else { 0 }) != 0
        }
    }

    /// Sets the flag to `old || value` and returns the old value.
    fn fetch_or(self, value: bool): bool {
        unsafe {
            __atomic_or_u32(self.cell, if value { 1 } else { 0 }) != 0
        }
    }

    /// Sets the flag to `old != value` and returns the old value.
    fn fetch_xor(self, value: bool): bool {
        unsafe {
            __atomic_xor_u32(self.cell, if value { 1 } else { 0 }) != 0
        }
    }
}

AtomicBool: Drop {
    fn drop(mut self) {
        unsafe {
            __dealloc(self.cell as CPtr<u8>, 4, 4)
        }
    }
}

unsafe AtomicBool: Send { }

unsafe AtomicBool: Sync { }
"""

INT = """
/// A `{ty}` that tasks and threads can read and write without a lock.
struct {name} {
    cell: CPtr<{word}>
}

{name} {
    /// A new atomic holding `value`.
    fn new(value: {ty}): {name} {
        unsafe {
            let cell = __alloc({bytes}, {bytes}) as CPtr<{word}>
            __atomic_store_{word}(cell, value as {word})
            {name} { cell: cell }
        }
    }

    /// The current value.
    fn load(self): {ty} {
        unsafe {
            __atomic_load_{word}(self.cell) as {ty}
        }
    }

    /// Writes `value`.
    fn store(self, value: {ty}) {
        unsafe {
            __atomic_store_{word}(self.cell, value as {word})
        }
    }

    /// Writes `value` and returns the value that was there.
    fn swap(self, value: {ty}): {ty} {
        unsafe {
            __atomic_swap_{word}(self.cell, value as {word}) as {ty}
        }
    }

    /// Writes `new` if the atomic holds `current`. `Ok(old)` when it did (and `old == current`), `Err(actual)` when it
    /// held something else and was left alone.
    fn compare_exchange(self, current: {ty}, new: {ty}): Result<{ty}, {ty}> {
        unsafe {
            let old = __atomic_cas_{word}(self.cell, current as {word}, new as {word}) as {ty}
            if old == current {
                Ok(old)
            } else {
                Err(old)
            }
        }
    }

    /// Adds `value` (wrapping around on overflow) and returns the value that was there.
    fn fetch_add(self, value: {ty}): {ty} {
        unsafe {
            __atomic_add_{word}(self.cell, value as {word}) as {ty}
        }
    }

    /// Subtracts `value` (wrapping around on overflow) and returns the value that was there.
    fn fetch_sub(self, value: {ty}): {ty} {
        unsafe {
            __atomic_sub_{word}(self.cell, value as {word}) as {ty}
        }
    }

    /// Sets the atomic to `old & value` and returns the old value.
    fn fetch_and(self, value: {ty}): {ty} {
        unsafe {
            __atomic_and_{word}(self.cell, value as {word}) as {ty}
        }
    }

    /// Sets the atomic to `old | value` and returns the old value.
    fn fetch_or(self, value: {ty}): {ty} {
        unsafe {
            __atomic_or_{word}(self.cell, value as {word}) as {ty}
        }
    }

    /// Sets the atomic to `old ^ value` and returns the old value.
    fn fetch_xor(self, value: {ty}): {ty} {
        unsafe {
            __atomic_xor_{word}(self.cell, value as {word}) as {ty}
        }
    }

    /// Sets the atomic to the larger of its value and `value` and returns the old value.
    fn fetch_max(self, value: {ty}): {ty} {
        loop {
            let current = self.load()
            if value <= current {
                return current
            }
            match self.compare_exchange(current, value) {
                Ok(old) => return old,
                Err(_) => {}
            }
        }
    }

    /// Sets the atomic to the smaller of its value and `value` and returns the old value.
    fn fetch_min(self, value: {ty}): {ty} {
        loop {
            let current = self.load()
            if value >= current {
                return current
            }
            match self.compare_exchange(current, value) {
                Ok(old) => return old,
                Err(_) => {}
            }
        }
    }
}

{name}: Drop {
    fn drop(mut self) {
        unsafe {
            __dealloc(self.cell as CPtr<u8>, {bytes}, {bytes})
        }
    }
}

unsafe {name}: Send { }

unsafe {name}: Sync { }
"""


# The doc example of each atomic type and method (issue #938). `{name}` is the type's name and `{ty}` its value type.
# Keys are a method name, or `struct` for the type itself. Every example is a doc test (`burdin test --doc` runs it).
INT_EXAMPLES = {
    "struct": ["let counter = {name}.new(0)", "counter.fetch_add(2)", "assert_eq(counter.load(), 2)"],
    "new": ["let x = {name}.new(3)", "assert_eq(x.load(), 3)"],
    "load": ["let x = {name}.new(3)", "assert_eq(x.load(), 3)"],
    "store": ["let x = {name}.new(0)", "x.store(9)", "assert_eq(x.load(), 9)"],
    "swap": ["let x = {name}.new(1)", "assert_eq(x.swap(4), 1)", "assert_eq(x.load(), 4)"],
    "compare_exchange": [
        "let x = {name}.new(1)",
        "assert_eq(x.compare_exchange(1, 2), Ok(1))",
        "assert_eq(x.compare_exchange(1, 3), Err(2))",
    ],
    "fetch_add": ["let x = {name}.new(5)", "assert_eq(x.fetch_add(2), 5)", "assert_eq(x.load(), 7)"],
    "fetch_sub": ["let x = {name}.new(5)", "assert_eq(x.fetch_sub(2), 5)", "assert_eq(x.load(), 3)"],
    "fetch_and": ["let x = {name}.new(6)", "assert_eq(x.fetch_and(3), 6)", "assert_eq(x.load(), 2)"],
    "fetch_or": ["let x = {name}.new(4)", "assert_eq(x.fetch_or(1), 4)", "assert_eq(x.load(), 5)"],
    "fetch_xor": ["let x = {name}.new(6)", "assert_eq(x.fetch_xor(3), 6)", "assert_eq(x.load(), 5)"],
    "fetch_max": [
        "let x = {name}.new(3)",
        "assert_eq(x.fetch_max(7), 3)",
        "assert_eq(x.fetch_max(1), 7)",
        "assert_eq(x.load(), 7)",
    ],
    "fetch_min": ["let x = {name}.new(3)", "assert_eq(x.fetch_min(1), 3)", "assert_eq(x.load(), 1)"],
}

BOOL_EXAMPLES = {
    "struct": ["let flag = AtomicBool.new(false)", "flag.store(true)", "assert(flag.load())"],
    "new": ["let flag = AtomicBool.new(true)", "assert(flag.load())"],
    "load": ["let flag = AtomicBool.new(true)", "assert(flag.load())"],
    "store": ["let flag = AtomicBool.new(false)", "flag.store(true)", "assert(flag.load())"],
    "swap": ["let flag = AtomicBool.new(false)", "assert_eq(flag.swap(true), false)", "assert(flag.load())"],
    "compare_exchange": [
        "let flag = AtomicBool.new(false)",
        "assert_eq(flag.compare_exchange(false, true), Ok(false))",
        "assert_eq(flag.compare_exchange(false, true), Err(true))",
    ],
    "fetch_and": ["let flag = AtomicBool.new(true)", "assert_eq(flag.fetch_and(false), true)", "assert(!flag.load())"],
    "fetch_or": ["let flag = AtomicBool.new(false)", "assert_eq(flag.fetch_or(true), false)", "assert(flag.load())"],
    "fetch_xor": ["let flag = AtomicBool.new(true)", "assert_eq(flag.fetch_xor(true), true)", "assert(!flag.load())"],
}


def with_examples(text: str, examples: dict, subs: dict) -> str:
    """Puts an example block at the end of the doc comment of each `struct` and `fn` that has one in `examples`."""
    out = []
    for line in text.split("\n"):
        indent = line[: len(line) - len(line.lstrip())]
        key = None
        method = re.match(r"\s*fn (\w+)\(", line)
        if method is not None:
            key = method.group(1)
        elif line.startswith("struct "):
            key = "struct"
        if key is not None and key in examples:
            out.append(f"{indent}///")
            out.append(f"{indent}/// ```")
            for example in examples[key]:
                for old, new in subs.items():
                    example = example.replace(old, new)
                out.append(f"{indent}/// {example}")
            out.append(f"{indent}/// ```")
        out.append(line)
    return "\n".join(out)


def render() -> str:
    out = HEADER + with_examples(BOOL, BOOL_EXAMPLES, {})
    for name, ty, word, bits in INTS:
        text = INT
        for key, value in (("{name}", name), ("{ty}", ty), ("{word}", word), ("{bytes}", str(bits // 8))):
            text = text.replace(key, value)
        out += with_examples(text, INT_EXAMPLES, {"{name}": name})
    return out


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if OUT.read_bytes().decode("utf-8").replace(chr(13), "") != text:
            print("std/src/atomic.bd is out of date: run python3 tests/gen_atomic_std.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
