#!/usr/bin/env python3
"""Generates std/src/int.bd: the integer functions of every integer type (issue #704).

Burdin has no numeric interface to write one generic body for all twelve integer types, so `std/src/int.bd` holds one
copy of each function per type, and this script writes them. Edit the templates here and run

    python3 tests/gen_int_std.py

`python3 tests/gen_int_std.py --check` fails when std/src/int.bd differs from the generated text (`tests/check_tests.py` runs it in CI).
"""

import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "std" / "src" / "int.bd"

TYPES = [
    # name, bits, signed
    ("i8", 8, True), ("i16", 16, True), ("i32", 32, True), ("i64", 64, True), ("isize", 64, True),
    ("u8", 8, False), ("u16", 16, False), ("u32", 32, False), ("u64", 64, False), ("usize", 64, False),
]

HEADER = """// The integer functions of every integer type (spec/stdlib.md, "Integer functions").
//
// GENERATED by tests/gen_int_std.py: edit the templates there, not this file. Burdin has no numeric interface to write
// one body for every type, so the functions exist once per integer type. They are extension methods (spec/extensions.md),
// so the prelude makes them visible everywhere; the methods the compiler provides (`wrapping_add`, `checked_add`,
// `min`, `max`, `abs`, `to_string`, `parse`) win. `u32.MAX`, `u32.from_le_bytes(b)`, and the other associated names
// are the `__<type>_<name>` constants and functions below: the compiler maps `T.name` to `__T_name`.

use std.ParseIntError
use unicode.to_digit
"""


def unsigned_of(name: str) -> str:
    return "u" + name[1:] if name.startswith("i") else name


def gen(name: str, bits: int, signed: bool) -> str:
    u = unsigned_of(name)
    t = name
    nbytes = bits // 8
    out = []
    w = out.append

    def fn(sig: str, doc: str, body: str) -> None:
        w(f"/// {doc}")
        w(f"fn {t}.{sig} {{")
        for line in body.strip("\n").split("\n"):
            w(("    " + line) if line.strip() else "")
        w("}")
        w("")

    def sfn(name_: str, params: str, ret: str, doc: str, body: str) -> None:
        w(f"/// {doc}")
        w(f"fn __{t}_{name_}({params}): {ret} {{")
        for line in body.strip("\n").split("\n"):
            w(("    " + line) if line.strip() else "")
        w("}")
        w("")

    w(f"// ---- {t} ----")
    w("")
    if signed:
        w(f"const __{t}_MIN: {t} = -{(1 << (bits - 1)) - 1} - 1")
        w(f"const __{t}_MAX: {t} = {(1 << (bits - 1)) - 1}")
    else:
        w(f"const __{t}_MIN: {t} = 0")
        w(f"const __{t}_MAX: {t} = {(1 << bits) - 1}")
    w(f"const __{t}_BITS: u32 = {bits}")
    w("")

    # ---- arithmetic ----
    fn("pow(self, exp: u32): " + t, "`self` to the power `exp`. Overflow panics in a debug build and wraps in a release build, like `*`.", f"""
let mut result: {t} = 1
let mut base = self
let mut e = exp
while e > 0 {{
    if e & 1 == 1 {{
        result = result * base
    }}
    e = e >> 1
    if e > 0 {{
        base = base * base
    }}
}}
result""")
    fn("wrapping_pow(self, exp: u32): " + t, "`self` to the power `exp`, wrapping around on overflow.", f"""
let mut result: {t} = 1
let mut base = self
let mut e = exp
while e > 0 {{
    if e & 1 == 1 {{
        result = result.wrapping_mul(base)
    }}
    e = e >> 1
    if e > 0 {{
        base = base.wrapping_mul(base)
    }}
}}
result""")
    fn(f"checked_pow(self, exp: u32): Option<{t}>", "`self` to the power `exp`, or `None` on overflow.", f"""
let mut result: {t} = 1
let mut base = self
let mut e = exp
while e > 0 {{
    if e & 1 == 1 {{
        match result.checked_mul(base) {{
            Some(v) => {{
                result = v
            }}
            None => {{
                return None
            }}
        }}
    }}
    e = e >> 1
    if e > 0 {{
        match base.checked_mul(base) {{
            Some(v) => {{
                base = v
            }}
            None => {{
                return None
            }}
        }}
    }}
}}
Some(result)""")
    if signed:
        overflow_div = f"(self == __{t}_MIN && other == -1)"
        fn(f"checked_div(self, other: {t}): Option<{t}>", "`self / other`, or `None` when `other` is 0 or the quotient overflows.", f"""
if other == 0 || {overflow_div} {{
    return None
}}
Some(self / other)""")
        fn(f"checked_rem(self, other: {t}): Option<{t}>", "`self % other`, or `None` when `other` is 0 or the division overflows.", f"""
if other == 0 || {overflow_div} {{
    return None
}}
Some(self % other)""")
        fn(f"checked_neg(self): Option<{t}>", "`-self`, or `None` for the minimum value.", f"""
if self == __{t}_MIN {{
    return None
}}
Some(0 - self)""")
        fn(f"wrapping_neg(self): {t}", "`-self`, wrapping around for the minimum value.", f"let zero: {t} = 0\nzero.wrapping_sub(self)")
    else:
        fn(f"checked_div(self, other: {t}): Option<{t}>", "`self / other`, or `None` when `other` is 0.", f"""
if other == 0 {{
    return None
}}
Some(self / other)""")
        fn(f"checked_rem(self, other: {t}): Option<{t}>", "`self % other`, or `None` when `other` is 0.", f"""
if other == 0 {{
    return None
}}
Some(self % other)""")
        fn(f"checked_neg(self): Option<{t}>", "`-self`: `Some(0)` for 0 and `None` for every other value.", f"""
if self == 0 {{
    return Some(0)
}}
None""")
        fn(f"wrapping_neg(self): {t}", "`-self`, wrapping around (two's complement).", f"let zero: {t} = 0\nzero.wrapping_sub(self)")

    fn(f"checked_shl(self, n: u32): Option<{t}>", "`self << n`, or `None` when `n` is the number of bits or more.", f"""
if n >= {bits} {{
    return None
}}
Some(self << n)""")
    fn(f"checked_shr(self, n: u32): Option<{t}>", "`self >> n`, or `None` when `n` is the number of bits or more.", f"""
if n >= {bits} {{
    return None
}}
Some(self >> n)""")
    fn(f"wrapping_shl(self, n: u32): {t}", "`self << (n % bits)`.", f"self << (n % {bits})")
    fn(f"wrapping_shr(self, n: u32): {t}", "`self >> (n % bits)`.", f"self >> (n % {bits})")

    if signed:
        sat_add = f"""
match self.checked_add(other) {{
    Some(v) => v,
    None => {{
        if other > 0 {{
            __{t}_MAX
        }} else {{
            __{t}_MIN
        }}
    }}
}}"""
        sat_sub = f"""
match self.checked_sub(other) {{
    Some(v) => v,
    None => {{
        if other > 0 {{
            __{t}_MIN
        }} else {{
            __{t}_MAX
        }}
    }}
}}"""
        sat_mul = f"""
match self.checked_mul(other) {{
    Some(v) => v,
    None => {{
        if (self < 0) == (other < 0) {{
            __{t}_MAX
        }} else {{
            __{t}_MIN
        }}
    }}
}}"""
        sat_pow = f"""
match self.checked_pow(exp) {{
    Some(v) => v,
    None => {{
        if self < 0 && exp % 2 == 1 {{
            __{t}_MIN
        }} else {{
            __{t}_MAX
        }}
    }}
}}"""
    else:
        sat_add = f"""
match self.checked_add(other) {{
    Some(v) => v,
    None => __{t}_MAX,
}}"""
        sat_sub = f"""
match self.checked_sub(other) {{
    Some(v) => v,
    None => 0,
}}"""
        sat_mul = sat_add.replace("checked_add", "checked_mul")
        sat_pow = f"""
match self.checked_pow(exp) {{
    Some(v) => v,
    None => __{t}_MAX,
}}"""
    fn(f"saturating_add(self, other: {t}): {t}", "`self + other`, clamped to the range of the type.", sat_add)
    fn(f"saturating_sub(self, other: {t}): {t}", "`self - other`, clamped to the range of the type.", sat_sub)
    fn(f"saturating_mul(self, other: {t}): {t}", "`self * other`, clamped to the range of the type.", sat_mul)
    fn(f"saturating_pow(self, exp: u32): {t}", "`self` to the power `exp`, clamped to the range of the type.", sat_pow)
    fn(f"overflowing_add(self, other: {t}): ({t}, bool)", "`self + other` wrapped, and whether it overflowed.", "(self.wrapping_add(other), self.checked_add(other).is_none())")
    fn(f"overflowing_sub(self, other: {t}): ({t}, bool)", "`self - other` wrapped, and whether it overflowed.", "(self.wrapping_sub(other), self.checked_sub(other).is_none())")
    fn(f"overflowing_mul(self, other: {t}): ({t}, bool)", "`self * other` wrapped, and whether it overflowed.", "(self.wrapping_mul(other), self.checked_mul(other).is_none())")

    if signed:
        fn(f"div_euclid(self, other: {t}): {t}", "The quotient rounded so that the remainder is never negative. Division by 0 panics.", """
let q = self / other
if self % other < 0 {
    if other > 0 {
        return q - 1
    }
    return q + 1
}
q""")
        fn(f"rem_euclid(self, other: {t}): {t}", "The remainder, never negative. Division by 0 panics.", """
let r = self % other
if r < 0 {
    if other > 0 {
        return r + other
    }
    return r - other
}
r""")
        fn(f"abs_diff(self, other: {t}): {u}", "The distance between `self` and `other`, as the unsigned type.", f"""
if self > other {{
    return (self.wrapping_sub(other)) as {u}
}}
(other.wrapping_sub(self)) as {u}""")
        fn(f"unsigned_abs(self): {u}", "The absolute value as the unsigned type, so the minimum value is representable.", f"""
if self < 0 {{
    let zero: {t} = 0
    return (zero.wrapping_sub(self)) as {u}
}}
self as {u}""")
        fn(f"signum(self): {t}", "`-1`, `0`, or `1` by the sign of `self`.", """
if self > 0 {
    return 1
}
if self < 0 {
    return 0 - 1
}
0""")
        fn("is_positive(self): bool", "Whether `self` is greater than 0.", "self > 0")
        fn("is_negative(self): bool", "Whether `self` is less than 0.", "self < 0")
    else:
        fn(f"div_euclid(self, other: {t}): {t}", "`self / other`. Division by 0 panics.", "self / other")
        fn(f"rem_euclid(self, other: {t}): {t}", "`self % other`. Division by 0 panics.", "self % other")
        fn(f"abs_diff(self, other: {t}): {t}", "The distance between `self` and `other`.", """
if self > other {
    return self - other
}
other - self""")

    # ---- bits ----
    to_u = f"self as {u}" if signed else "self"
    fn("count_ones(self): u32", "The number of 1 bits.", f"""
let mut v: {u} = {to_u}
let mut n: u32 = 0
while v != 0 {{
    n = n + (v & 1) as u32
    v = v >> 1
}}
n""")
    fn("count_zeros(self): u32", "The number of 0 bits.", f"{bits} - self.count_ones()")
    fn("leading_zeros(self): u32", "The number of 0 bits before the first 1 bit, from the top.", f"""
let v: {u} = {to_u}
let mut n: u32 = 0
let mut i: u32 = {bits}
while i > 0 {{
    i = i - 1
    if (v >> i) & 1 == 1 {{
        return n
    }}
    n = n + 1
}}
n""")
    fn("trailing_zeros(self): u32", "The number of 0 bits after the last 1 bit, from the bottom.", f"""
let v: {u} = {to_u}
let mut n: u32 = 0
while n < {bits} {{
    if (v >> n) & 1 == 1 {{
        return n
    }}
    n = n + 1
}}
n""")
    fn(f"rotate_left(self, n: u32): {t}", "The bits rotated left by `n % bits` places.", f"""
let v: {u} = {to_u}
let k = n % {bits}
if k == 0 {{
    return self
}}
let back: u32 = {bits} - k
((v << k) | (v >> back)) as {t}""")
    fn(f"rotate_right(self, n: u32): {t}", "The bits rotated right by `n % bits` places.", f"""
let v: {u} = {to_u}
let k = n % {bits}
if k == 0 {{
    return self
}}
let back: u32 = {bits} - k
((v >> k) | (v << back)) as {t}""")
    fn(f"swap_bytes(self): {t}", "The bytes in the opposite order.", f"""
let v: {u} = {to_u}
let mut r: {u} = 0
let mut i: u32 = 0
while i < {nbytes} {{
    let shift: u32 = 8 * i
    r = (r << 8) | ((v >> shift) & 255)
    i = i + 1
}}
r as {t}""")
    fn(f"reverse_bits(self): {t}", "The bits in the opposite order.", f"""
let v: {u} = {to_u}
let mut r: {u} = 0
let mut i: u32 = 0
while i < {bits} {{
    r = (r << 1) | ((v >> i) & 1)
    i = i + 1
}}
r as {t}""")
    if not signed:
        fn("is_power_of_two(self): bool", "Whether exactly one bit is set.", "self != 0 && self & (self - 1) == 0")
        fn(f"checked_next_power_of_two(self): Option<{t}>", "The smallest power of two that is at least `self`, or `None` when it does not fit.", f"""
if self <= 1 {{
    return Some(1)
}}
let top = {bits} - (self - 1).leading_zeros()
if top >= {bits} {{
    return None
}}
Some(1 << top)""")
        fn(f"next_power_of_two(self): {t}", "The smallest power of two that is at least `self`. It panics when the result does not fit.", f"""
match self.checked_next_power_of_two() {{
    Some(v) => v,
    None => panic("next_power_of_two overflowed"),
}}""")

    # ---- isqrt and logarithms ----
    sqrt_body = f"""
let mut n: {u} = {"self as " + u if signed else "self"}
let mut result: {u} = 0
let mut bit: {u} = 1 << {bits - 2}
while bit > n {{
    bit = bit >> 2
}}
while bit != 0 {{
    if n >= result + bit {{
        n = n - (result + bit)
        result = (result >> 1) + bit
    }} else {{
        result = result >> 1
    }}
    bit = bit >> 2
}}
result{" as " + t if signed else ""}"""
    if signed:
        sqrt_body = f"""
if self < 0 {{
    panic("isqrt of a negative number")
}}""" + sqrt_body
    fn(f"isqrt(self): {t}", "The integer square root: the greatest `r` with `r * r <= self`." + (" A negative `self` panics." if signed else ""), sqrt_body)
    guard = ""
    fn("ilog2(self): u32", "The base 2 logarithm rounded down. A `self` that is 0" + (" or negative" if signed else "") + " panics.", f"""
if self <= 0 {{
    panic("ilog2 of a number that is not positive")
}}
{bits - 1} - self.leading_zeros()""")
    fn("ilog10(self): u32", "The base 10 logarithm rounded down. A `self` that is 0" + (" or negative" if signed else "") + " panics.", f"""
if self <= 0 {{
    panic("ilog10 of a number that is not positive")
}}
let mut v = self
let mut n: u32 = 0
while v >= 10 {{
    v = v / 10
    n = n + 1
}}
n""")

    # ---- text in a base ----
    if signed:
        sign_branch = f"""
    if first {{
        first = false
        if c == '-' {{
            negative = true
            continue
        }}
    }}"""
        accumulate = f"""
            let digit: {t} = d as {t}
            let scaled = value.checked_mul(base)
            if scaled.is_none() {{
                return Err(ParseIntError.Invalid)
            }}
            let next = if negative {{ scaled.unwrap().checked_sub(digit) }} else {{ scaled.unwrap().checked_add(digit) }}
            if next.is_none() {{
                return Err(ParseIntError.Invalid)
            }}
            value = next.unwrap()"""
        neg_decl = "let mut negative = false\n"
    else:
        sign_branch = ""
        accumulate = f"""
            let digit: {t} = d as {t}
            let scaled = value.checked_mul(base)
            if scaled.is_none() {{
                return Err(ParseIntError.Invalid)
            }}
            let next = scaled.unwrap().checked_add(digit)
            if next.is_none() {{
                return Err(ParseIntError.Invalid)
            }}
            value = next.unwrap()"""
        neg_decl = ""
    first_decl = "let mut first = true\n" if signed else ""
    sfn("parse_radix", "s: str, radix: u32", f"Result<{t}, ParseIntError>",
        "The number in the text in base `radix` (2 to 36; any other radix panics). " + ("An optional leading `-` is allowed. " if signed else "") + "Any failure (no digits, a character that is not a digit of the base, or a value out of range) is `ParseIntError.Invalid`.", f"""
if radix < 2 || radix > 36 {{
    panic("parse_radix: radix must be 2 to 36")
}}
let base: {t} = radix as {t}
let mut value: {t} = 0
let mut seen_digit = false
{neg_decl}{first_decl}for c in s.chars() {{{sign_branch}
    match c.to_digit(radix) {{
        Some(d) => {{{accumulate}
            seen_digit = true
        }}
        None => {{
            return Err(ParseIntError.Invalid)
        }}
    }}
}}
if !seen_digit {{
    return Err(ParseIntError.Invalid)
}}
Ok(value)""")
    magnitude = "self.unsigned_abs()" if signed else "self"
    neg_prefix = "if self < 0 {\n    out.push('-')\n}\n" if signed else ""
    fn("to_string_radix(self, radix: u32): String", "The number written in base `radix` (2 to 36, lowercase digits; any other radix panics), with a leading `-` when negative.", f"""
if radix < 2 || radix > 36 {{
    panic("to_string_radix: radix must be 2 to 36")
}}
let mut out = String.new()
{neg_prefix}let mut v: {u} = {magnitude}
if v == 0 {{
    out.push('0')
    return out
}}
let base: {u} = radix as {u}
let mut digits = List<char>.new()
while v > 0 {{
    let d = (v % base) as u32
    if d < 10 {{
        digits.push((48 + d) as char)
    }} else {{
        digits.push((87 + d) as char)
    }}
    v = v / base
}}
let mut i = digits.len()
while i > 0 {{
    i = i - 1
    out.push(digits[i])
}}
out""")

    # ---- bytes ----
    le_items = ", ".join(f"((v >> {8 * i}) & 255) as u8" for i in range(nbytes))
    be_items = ", ".join(f"((v >> {8 * (nbytes - 1 - i)}) & 255) as u8" for i in range(nbytes))
    fn(f"to_le_bytes(self): [u8; {nbytes}]", "The bytes in little-endian order.", f"""
let v: {u} = {to_u}
[{le_items}]""")
    fn(f"to_be_bytes(self): [u8; {nbytes}]", "The bytes in big-endian order.", f"""
let v: {u} = {to_u}
[{be_items}]""")
    fn(f"to_ne_bytes(self): [u8; {nbytes}]", "The bytes in the byte order of the target, which is little-endian on every supported platform.", "self.to_le_bytes()")
    from_le = " | ".join(f"((b[{i}] as {u}) << {8 * i})" for i in range(nbytes))
    from_be = " | ".join(f"((b[{i}] as {u}) << {8 * (nbytes - 1 - i)})" for i in range(nbytes))
    cast = f" as {t}" if signed else ""
    sfn("from_le_bytes", f"b: [u8; {nbytes}]", t, "The value whose little-endian bytes are `b`.", f"""
let v: {u} = {from_le}
v{cast}""")
    sfn("from_be_bytes", f"b: [u8; {nbytes}]", t, "The value whose big-endian bytes are `b`.", f"""
let v: {u} = {from_be}
v{cast}""")
    sfn("from_ne_bytes", f"b: [u8; {nbytes}]", t, "The value whose native-endian bytes are `b`.", f"__{t}_from_le_bytes(b)")
    return "\n".join(out)


def render() -> str:
    return HEADER + "\n" + "\n".join(gen(*spec) for spec in TYPES)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("std/src/int.bd is out of date: run python3 tests/gen_int_std.py", file=sys.stderr)
            return 1
        print("std/src/int.bd is up to date.")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
