#!/usr/bin/env python3
"""Checks dependency tables, features, and target-specific dependencies (stage 3, issues #340 and #341;
spec/packages.md, PKG25-PKG33).

Needs a built driver (BURDIN selects it, like tests/run_tests.py).

What it checks:
  * `[features]` and `--features`/`--no-default-features`/`--all-features` decide the constants of the generated
    `features` module, and a program branches on them with a plain `if` on the constants (PKG28, PKG29, PKG32);
  * a feature forwards to a dependency's feature (`x/feature`) and an optional dependency is switched by `dep:x`
    (PKG28);
  * features unify across the graph: two dependents request different features of one package and both are enabled,
    although neither edge asks for both (PKG30);
  * a request for an inactive dependency is ignored on this platform (PKG30);
  * the `[features]` table is validated when the manifest is read, and an unknown `--features` item is an error
    (PKG28, PKG29);
  * a dev-dependency is invisible to `build`, `run`, and `check`, and visible to `test` and `check --tests` through
    its package name; a missing dev-dependency path is an error in every build (PKG26);
  * a dependency's own dev-dependencies are never loaded (PKG26);
  * a target-specific dependency of another platform is not loaded, and one of this platform is (PKG27);
  * an unknown predicate and a bare target triple are errors, and a target-specific dev-dependency follows the
    platform too (PKG27);
  * a one-file target takes no feature flags (PKG31);
  * `burdin.lock` pins the potential graph (optional, dev, and every target's dependencies, and what a dev-dependency
    reaches), `--locked` accepts it, and features and the command leave it unchanged (PKG33);
  * a source module named `features` conflicts with the generated one, and a package with neither features nor an
    optional dependency has no such module (PKG32);
  * a workspace member's dev-dependency reaches its test through `-p`, and `--offline` and `--locked` build a
    path-only workspace (PKG24, PKG26, WS19);
  * a dev-dependency's code is in the test executable and not in the executable of `build` (PKG26, issue #341).
"""

import os
import sys
from pathlib import Path

import harness

problems = []
checks = 0


def check(condition: bool, message: str) -> None:
    global checks
    checks += 1
    if not condition:
        problems.append(message)


burdin = harness.require_burdin()
PLATFORM = harness.PLATFORM
UNIX = PLATFORM in ("linux", "macos")

HEADER = (
    "# burdin.lock: the exact packages this package builds with. It is generated by burdin;\n"
    "# do not edit it by hand.\n"
    "version = 1\n"
)


def lock_package(name, dependencies=(), version=None):
    lines = ["", "[[package]]", f'name = "{name}"']
    if version is not None:
        lines.append(f'version = "{version}"')
    lines.append("dependencies = [" + ", ".join(f'"{d}"' for d in dependencies) + "]")
    return "\n".join(lines) + "\n"


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    harness.write_text(path, content)


def package(work: Path, name: str, manifest: str, modules: dict) -> Path:
    directory = work / name
    for relative, body in modules.items():
        write(directory / "src" / relative, body)
    write(directory / "burdin.toml", manifest)
    return directory


def out(result) -> str:
    return harness.text(result.stdout).replace("\r", "")


def err(result) -> str:
    return harness.text(result.stderr).replace("\r", "")


# A dependency whose two features add to its answer. `default` enables `polite`.
GREET_MANIFEST = """[package]
name = "greet"
version = "0.1.0"

[features]
default = ["polite"]
loud = []
polite = []
"""
GREET_BODY = """use features.loud
use features.polite

fn answer(): i32 {
    let base = 5
    let loud_part = if loud { 2 } else { 0 }
    let polite_part = if polite { 1 } else { 0 }
    base + loud_part + polite_part
}
"""

APP_MANIFEST = """[package]
name = "app"
version = "0.1.0"

[dependencies]
greet = { path = "../greet", default-features = false, features = ["loud"] }
extra = { path = "../extra", optional = true }

[features]
default = ["fast"]
fast = ["dep:extra"]
slow = ["greet/polite"]
"""
APP_BODY = """use greet.answer
use features.fast
use features.slow
use features.extra

fn main() {
    println("{answer()}")
    if fast {
        println("fast on")
    } else {
        println("fast off")
    }
    if slow {
        println("slow on")
    } else {
        println("slow off")
    }
    if extra {
        println("extra on")
    } else {
        println("extra off")
    }
}

test "the selected features reach the test build" {
    assert(!fast)?
    assert(slow)?
    assert_eq(answer(), 8)?
}
"""

with harness.temporary_dir("burdin-features-") as work:
    env = dict(os.environ)
    env["BURDIN_HOME"] = str(work / "home")

    def run_in(directory, *arguments):
        return harness.run([burdin, *arguments], cwd=directory, env=env)

    package(work, "greet", GREET_MANIFEST, {"greet.bd": GREET_BODY})
    package(work, "extra", '[package]\nname = "extra"\n', {"extra.bd": "fn bonus(): i32 {\n    1\n}\n"})
    package(work, "testkit", '[package]\nname = "testkit"\n', {"testkit.bd": "fn answer(): i32 {\n    3\n}\n"})
    package(work, "inner", '[package]\nname = "inner"\n', {"inner.bd": "fn inner_answer(): i32 {\n    2\n}\n"})
    package(
        work,
        "unixonly",
        '[package]\nname = "unixonly"\n',
        {"unixonly.bd": "fn platform(): i32 {\n    1\n}\n"},
    )
    # A source that does not parse: loading it is the witness that its package was loaded.
    package(work, "winbroken", '[package]\nname = "winbroken"\n', {"winbroken.bd": "fn broken(: i32 {\n}\n"})
    package(work, "brokenkit", '[package]\nname = "brokenkit"\n', {"brokenkit.bd": "fn broken(: i32 {\n}\n"})
    # The lockfile fixture uses a Windows-only dependency, so its source must parse on Windows too.
    package(work, "winonly", '[package]\nname = "winonly"\n', {"winonly.bd": "fn sentinel(): i32 {\n    1\n}\n"})
    app = package(work, "app", APP_MANIFEST, {"main.bd": APP_BODY})

    # --- Selecting the features of the entry package -------------------------------------------------------------
    for flags, expected, description in (
        ([], "7\nfast on\nslow off\nextra on\n", "the default features"),
        (["--no-default-features"], "7\nfast off\nslow off\nextra off\n", "--no-default-features"),
        (
            ["--no-default-features", "--features", "slow"],
            "8\nfast off\nslow on\nextra off\n",
            "--features slow",
        ),
        (["--all-features"], "8\nfast on\nslow on\nextra on\n", "--all-features"),
        (["--all-features", "--no-default-features"], "8\nfast on\nslow on\nextra on\n", "both all and no-default"),
        (["--features", "fast,slow"], "8\nfast on\nslow on\nextra on\n", "a comma-separated list"),
        (["--features", "fast", "--features", "slow"], "8\nfast on\nslow on\nextra on\n", "a repeated flag"),
    ):
        result = run_in(app, "run", ".", *flags)
        check(
            result.returncode == 0 and out(result) == expected,
            f"`burdin run . {' '.join(flags)}` with {description} gave {result.returncode}: "
            f"{out(result)!r} {err(result)[:300]}",
        )
    checked = run_in(app, "check", ".", "--no-default-features", "--features", "slow")
    check(checked.returncode == 0, f"`burdin check . --features slow` failed: {err(checked)[:300]}")
    tested = run_in(app, "test", ".", "--no-default-features", "--features", "slow")
    check(
        tested.returncode == 0 and "1 passed, 0 failed" in out(tested),
        f"`burdin test . --features slow` gave {tested.returncode}: {out(tested)!r} {err(tested)[:300]}",
    )

    # --- Unification across the graph ----------------------------------------------------------------------------
    package(
        work,
        "one",
        '[package]\nname = "one"\n\n[dependencies]\ngreet = { path = "../greet", default-features = false, '
        'features = ["loud"] }\n',
        {"one.bd": "fn one_answer(): i32 {\n    greet.answer()\n}\n"},
    )
    package(
        work,
        "two",
        '[package]\nname = "two"\n\n[dependencies]\ngreet = { path = "../greet", default-features = false, '
        'features = ["polite"] }\n',
        {"two.bd": "fn two_answer(): i32 {\n    greet.answer()\n}\n"},
    )
    multi = package(
        work,
        "multi",
        '[package]\nname = "multi"\n\n[dependencies]\none = { path = "../one" }\ntwo = { path = "../two" }\n',
        {"main.bd": 'fn main() {\n    println("{one.one_answer()} {two.two_answer()}")\n}\n'},
    )
    unified = run_in(multi, "run", ".")
    check(
        unified.returncode == 0 and out(unified) == "8 8\n",
        f"the features of `greet` did not unify across `one` and `two`: {out(unified)!r} {err(unified)[:300]}",
    )
    # A dependency that asks for nothing gets `default`; one that disables defaults does not.
    justgreet = package(
        work,
        "justgreet",
        '[package]\nname = "justgreet"\n\n[dependencies]\ngreet = { path = "../greet" }\n',
        {"main.bd": 'fn main() {\n    println("{greet.answer()}")\n}\n'},
    )
    defaulted = run_in(justgreet, "run", ".")
    check(
        defaulted.returncode == 0 and out(defaulted) == "6\n",
        f"a dependency's `default` feature is not enabled by default: {out(defaulted)!r} {err(defaulted)[:300]}",
    )

    # A request for a dependency this platform does not select is ignored (PKG30).
    winfeature = package(
        work,
        "winfeature",
        "[package]\nname = \"winfeature\"\n\n[target.'cfg(windows)'.dependencies]\n"
        'extra = { path = "../extra", features = ["nope"] }\n',
        {"main.bd": 'fn main() {\n    println("ok")\n}\n'},
    )
    ignored = run_in(winfeature, "build", ".")
    if PLATFORM == "windows":
        check(
            ignored.returncode == 1 and "package `extra` has no feature `nope`" in err(ignored),
            f"the active platform's request for a missing feature is not an error: {err(ignored)[:300]}",
        )
    else:
        check(
            ignored.returncode == 0,
            f"a request for an inactive dependency was not ignored: {err(ignored)[:300]}",
        )

    # --- Dev-dependencies (PKG26) --------------------------------------------------------------------------------
    devapp = package(
        work,
        "devapp",
        '[package]\nname = "devapp"\n\n[dev-dependencies]\ntestkit = { path = "../testkit" }\n',
        {
            "main.bd": 'fn main() {\n    println("built")\n}\n\n'
            'test "the kit" {\n    assert_eq(testkit.answer(), 3)?\n}\n'
        },
    )
    broken_testkit = """fn answer(: i32 {
    3
}
"""
    write(work / "testkit" / "src" / "testkit.bd", broken_testkit)
    built = run_in(devapp, "build", ".")
    check(
        built.returncode == 0,
        f"a broken dev-dependency's source stopped `burdin build`: {err(built)[:300]}",
    )
    ran = run_in(devapp, "run", ".")
    check(ran.returncode == 0 and out(ran) == "built\n", f"`burdin run` with a broken dev-dependency failed: {err(ran)[:300]}")
    checked = run_in(devapp, "check", ".")
    check(checked.returncode == 0, f"`burdin check` read a dev-dependency: {err(checked)[:300]}")
    for command in (["test", "."], ["check", ".", "--tests"]):
        failed = run_in(devapp, *command)
        check(
            failed.returncode == 1 and "testkit.bd:1" in err(failed),
            f"`burdin {' '.join(command)}` did not compile the dev-dependency: {err(failed)[:300]}",
        )
    write(work / "testkit" / "src" / "testkit.bd", "fn answer(): i32 {\n    3\n}\n")
    tested = run_in(devapp, "test", ".")
    check(
        tested.returncode == 0 and "1 passed, 0 failed" in out(tested),
        f"the test did not reach its dev-dependency: {out(tested)!r} {err(tested)[:300]}",
    )
    checked = run_in(devapp, "check", ".", "--tests")
    check(checked.returncode == 0, f"`burdin check --tests` failed with a valid dev-dependency: {err(checked)[:300]}")
    # The dev-dependency is visible to a test only: ordinary code cannot name it.
    write(
        devapp / "src" / "main.bd",
        'fn main() {\n    println("built")\n}\n\nfn oops(): i32 {\n    testkit.answer()\n}\n',
    )
    leaked = run_in(devapp, "build", ".")
    check(
        leaked.returncode == 1 and "E0002" in err(leaked) and "testkit" in err(leaked),
        f"ordinary code reached a dev-dependency: {err(leaked)[:300]}",
    )
    write(
        devapp / "src" / "main.bd",
        'fn main() {\n    println("built")\n}\n\n'
        'test "the kit" {\n    assert_eq(testkit.answer(), 3)?\n}\n',
    )

    # A missing dev-dependency path fails every build: its manifest is pinned for the lockfile (PKG26, PKG33).
    missing = package(
        work,
        "missing",
        '[package]\nname = "missing"\n\n[dev-dependencies]\ngone = { path = "../gone" }\n',
        {"main.bd": 'fn main() {\n    println("x")\n}\n'},
    )
    absent = run_in(missing, "build", ".")
    check(
        absent.returncode == 1 and "dependency `gone`" in err(absent),
        f"a missing dev-dependency path is not an error in a build: {err(absent)[:300]}",
    )

    # A dependency's own dev-dependencies are never loaded.
    package(
        work,
        "lib",
        '[package]\nname = "lib"\n\n[dev-dependencies]\nlibdev = { path = "../libdev" }\n',
        {"lib.bd": "fn lib_answer(): i32 {\n    4\n}\n"},
    )
    package(work, "libdev", '[package]\nname = "libdev"\n', {"libdev.bd": "fn broken(: i32 {\n}\n"})
    libapp = package(
        work,
        "libapp",
        '[package]\nname = "libapp"\n\n[dependencies]\nlib = { path = "../lib" }\n',
        {"main.bd": 'fn main() {\n    println("{lib.lib_answer()}")\n}\n'},
    )
    lib_build = run_in(libapp, "build", ".")
    check(
        lib_build.returncode == 0,
        f"a dependency's own dev-dependency was loaded: {err(lib_build)[:300]}",
    )

    # --- Target-specific dependencies (PKG27) --------------------------------------------------------------------
    winapp = package(
        work,
        "winapp",
        "[package]\nname = \"winapp\"\n\n[target.'cfg(windows)'.dependencies]\n"
        'winbroken = { path = "../winbroken" }\n',
        {"main.bd": 'fn main() {\n    println("host")\n}\n'},
    )
    windows_dep = run_in(winapp, "run", ".")
    if PLATFORM == "windows":
        check(
            windows_dep.returncode == 1 and "winbroken.bd:1" in err(windows_dep),
            f"a Windows-only dependency was not loaded on Windows: {err(windows_dep)[:300]}",
        )
    else:
        check(
            windows_dep.returncode == 0 and out(windows_dep) == "host\n",
            f"a Windows-only dependency was loaded on {PLATFORM}: {err(windows_dep)[:300]}",
        )

    unixapp = package(
        work,
        "unixapp",
        "[package]\nname = \"unixapp\"\n\n[target.'cfg(unix)'.dependencies]\n"
        'unixonly = { path = "../unixonly" }\n',
        {"main.bd": 'use unixonly.platform\n\nfn main() {\n    println("{platform()}")\n}\n'},
    )
    unix_dep = run_in(unixapp, "run", ".")
    if UNIX:
        check(
            unix_dep.returncode == 0 and out(unix_dep) == "1\n",
            f"a `cfg(unix)` dependency was not loaded on {PLATFORM}: {err(unix_dep)[:300]}",
        )
    else:
        check(
            unix_dep.returncode == 1 and "E0002" in err(unix_dep),
            f"a `cfg(unix)` dependency was loaded on {PLATFORM}: {err(unix_dep)[:300]}",
        )

    # A target-specific dev-dependency follows the platform too.
    devtarget = package(
        work,
        "devtarget",
        f"[package]\nname = \"devtarget\"\n\n[target.'cfg(target_os = \"{PLATFORM}\")'.dev-dependencies]\n"
        'brokenkit = { path = "../brokenkit" }\n',
        {"main.bd": 'fn main() {\n    println("ok")\n}\n'},
    )
    built = run_in(devtarget, "build", ".")
    check(built.returncode == 0, f"a dev-dependency was read by a build: {err(built)[:300]}")
    checked = run_in(devtarget, "check", ".", "--tests")
    check(
        checked.returncode == 1 and "brokenkit.bd:1" in err(checked),
        f"a target-specific dev-dependency of this platform was not loaded by `check --tests`: {err(checked)[:300]}",
    )

    # --- Malformed manifests and command lines -------------------------------------------------------------------
    bad = package(work, "bad", "[package]\nname = \"bad\"\n", {"main.bd": "fn main() {}\n"})
    for manifest, message in (
        (
            '[package]\nname = "bad"\n\n[features]\nfast = ["ok"]\n',
            "which is not a feature or an optional dependency",
        ),
        (
            '[package]\nname = "bad"\n\n[dependencies]\nextra = { path = "../extra" }\n\n'
            '[features]\nfast = ["dep:extra"]\n',
            "but `extra` is not an optional dependency",
        ),
        ('[package]\nname = "bad"\n\n[features]\nfast = ["nope/loud"]\n', "but `nope` is not a dependency"),
        (
            '[package]\nname = "bad"\n\n[dependencies]\nextra = { path = "../extra", optional = true }\n\n'
            "[features]\nextra = []\n",
            "has the name of an optional dependency",
        ),
        (
            '[package]\nname = "bad"\n\n[dev-dependencies]\ntestkit = { path = "../testkit" }\n\n'
            '[features]\nfast = ["testkit/loud"]\n',
            "is a dev-dependency, which no feature can enable",
        ),
        ('[package]\nname = "bad"\n\n[features]\n"not ok" = []\n', "is not a feature name"),
        (
            "[package]\nname = \"bad\"\n\n[target.'cfg(bogus)'.dependencies]\nextra = { path = \"../extra\" }\n",
            "unknown predicate `bogus`",
        ),
        (
            '[package]\nname = "bad"\n\n[target.x86_64-unknown-linux-gnu.dependencies]\nextra = { path = "../extra" }\n',
            "a target table is",
        ),
    ):
        write(bad / "burdin.toml", manifest)
        rejected = run_in(bad, "build", ".")
        check(
            rejected.returncode == 1 and message in err(rejected),
            f"the manifest `{manifest!r}` did not fail with {message!r}: {err(rejected)[:300]}",
        )
    write(bad / "burdin.toml", "[package]\nname = \"bad\"\n")
    unknown = run_in(bad, "build", ".", "--features", "nope")
    check(
        unknown.returncode == 1 and "package `bad` has no feature `nope`" in err(unknown),
        f"an unknown `--features` item is not an error: {err(unknown)[:300]}",
    )

    # A one-file target has no features (PKG31).
    script = work / "script.bd"
    write(script, 'fn main() {\n    println("one")\n}\n')
    for flag in (["--no-default-features"], ["--all-features"], ["--features", "x"]):
        refused = run_in(work, "run", script.name, *flag)
        check(
            refused.returncode == 1 and "a one-file target has no features" in err(refused),
            f"`burdin run script.bd {' '.join(flag)}` was not refused: {refused.returncode} {err(refused)[:300]}",
        )

    # --- The generated `features` module (PKG32) -----------------------------------------------------------------
    plain = package(work, "plain", '[package]\nname = "plain"\n', {"main.bd": 'fn main() {\n    println("plain")\n}\n'})
    plain_run = run_in(plain, "run", ".")
    check(plain_run.returncode == 0 and out(plain_run) == "plain\n", f"a package without features did not run: {err(plain_run)[:300]}")
    write(plain / "src" / "main.bd", "use features.fast\n\nfn main() {}\n")
    no_module = run_in(plain, "build", ".")
    check(
        no_module.returncode == 1 and "E0002" in err(no_module) and "features.fast" in err(no_module),
        f"a package without features got a `features` module: {err(no_module)[:300]}",
    )
    clash = package(work, "clash", '[package]\nname = "clash"\n\n[features]\nfast = []\n', {"main.bd": "fn main() {}\n"})
    write(clash / "src" / "features.bd", "fn g() {}\n")
    conflict = run_in(clash, "build", ".")
    check(
        conflict.returncode == 1 and "has a module `features`" in err(conflict),
        f"a source module named `features` is not refused: {err(conflict)[:300]}",
    )

    # --- The lockfile pins the potential graph (PKG33) -----------------------------------------------------------
    lockapp = package(
        work,
        "lockapp",
        """[package]
name = "lockapp"
version = "1.0.0"

[dependencies]
greet = { path = "../greet" }
extra = { path = "../extra", optional = true }

[dev-dependencies]
testkit = { path = "../testkit" }

[target.'cfg(windows)'.dependencies]
winonly = { path = "../winonly" }
""",
        {"main.bd": 'fn main() {\n    println("locked")\n}\n'},
    )
    write(work / "testkit" / "burdin.toml", '[package]\nname = "testkit"\n\n[dependencies]\ninner = { path = "../inner" }\n')
    golden = HEADER + "".join(
        [
            lock_package("extra"),
            lock_package("greet", version="0.1.0"),
            lock_package("inner"),
            lock_package("lockapp", ["extra", "greet", "testkit", "winonly"], version="1.0.0"),
            lock_package("testkit", ["inner"]),
            lock_package("winonly"),
        ]
    )
    write(lockapp / "burdin.lock", golden)
    locked = run_in(lockapp, "run", ".", "--locked")
    check(
        locked.returncode == 0 and out(locked) == "locked\n",
        f"`--locked` rejected the potential graph: {err(locked)[:400]}",
    )
    check(harness.read_text(lockapp / "burdin.lock") == golden, "a build rewrote a current lockfile")
    for arguments in (
        ["build", ".", "--locked", "--all-features"],
        ["check", ".", "--locked", "--no-default-features"],
        ["test", ".", "--locked"],
    ):
        result = run_in(lockapp, *arguments)
        check(
            result.returncode == 0,
            f"`burdin {' '.join(arguments)}` failed on the potential graph: {err(result)[:400]}",
        )
        check(
            harness.read_text(lockapp / "burdin.lock") == golden,
            f"`burdin {' '.join(arguments)}` changed the lockfile",
        )

    # --- A test-only dependency is not linked into a normal build (issue #341, PKG26) ----------------------------
    # The dependency returns a string only the test uses. Its bytes must be in the test executable (the positive
    # control) and absent from the executable of `build`, which never loads the dependency.
    sentinel = b"dev-only-sentinel-7531"
    package(
        work,
        "sentinelkit",
        '[package]\nname = "sentinelkit"\n',
        {"sentinelkit.bd": 'fn label(): str {\n    "dev-only-sentinel-7531"\n}\n'},
    )
    linked = package(
        work,
        "linked",
        '[package]\nname = "linked"\n\n[dev-dependencies]\nsentinelkit = { path = "../sentinelkit" }\n',
        {
            "main.bd": 'fn main() {\n    println("normal")\n}\n\n'
            'test "the sentinel" {\n    assert_eq(sentinelkit.label(), "dev-only-sentinel-7531")?\n}\n'
        },
    )
    built_normal = run_in(linked, "build", ".")
    check(built_normal.returncode == 0, f"`build` of a package with a dev-dependency failed: {err(built_normal)[:300]}")
    suffix = ".exe" if PLATFORM == "windows" else ""
    normal_exe = linked / "target" / "burdin" / "debug" / "bin" / f"linked{suffix}"
    check(normal_exe.is_file(), f"`build` wrote no executable at {normal_exe}")
    check(
        normal_exe.is_file() and sentinel not in normal_exe.read_bytes(),
        "a test-only dependency's code is linked into the executable of a normal build",
    )
    tested_linked = run_in(linked, "test", ".")
    check(
        tested_linked.returncode == 0 and "1 passed, 0 failed" in out(tested_linked),
        f"`test` did not reach the dev-dependency: {out(tested_linked)!r} {err(tested_linked)[:300]}",
    )
    test_exe = linked / "target" / "burdin" / "debug" / "test" / f"linked{suffix}"
    check(
        test_exe.is_file() and sentinel in test_exe.read_bytes(),
        "positive control: the test executable does not contain the dev-dependency's string",
    )

    # --- A workspace member's dev-dependency, and --offline (PKG24, PKG26; WS19) ---------------------------------
    # The dev-dependency lives outside the workspace, reached by a relative path from the member.
    package(work, "wsdev", '[package]\nname = "wsdev"\n', {"wsdev.bd": "fn answer(): i32 {\n    3\n}\n"})
    wsroot = work / "wsroot"
    write(wsroot / "burdin.toml", '[workspace]\nmembers = ["apps/*"]\n')
    package(
        wsroot / "apps",
        "wsapp",
        '[package]\nname = "wsapp"\n\n[dev-dependencies]\nwsdev = { path = "../../../wsdev" }\n',
        {
            "main.bd": 'fn main() {\n    println("workspace")\n}\n\n'
            'test "the workspace kit" {\n    assert_eq(wsdev.answer(), 3)?\n}\n'
        },
    )
    ws_built = run_in(wsroot, "build", ".", "-p", "wsapp")
    check(ws_built.returncode == 0, f"`build -p wsapp` of a workspace member failed: {err(ws_built)[:300]}")
    ws_tested = run_in(wsroot, "test", ".", "-p", "wsapp")
    check(
        ws_tested.returncode == 0 and "1 passed, 0 failed" in out(ws_tested),
        f"`test -p wsapp` did not reach its dev-dependency: {out(ws_tested)!r} {err(ws_tested)[:300]}",
    )
    ws_checked = run_in(wsroot / "apps" / "wsapp", "check", ".", "--tests")
    check(ws_checked.returncode == 0, f"`check --tests` in a workspace member failed: {err(ws_checked)[:300]}")
    ws_ran = run_in(wsroot, "run", ".", "-p", "wsapp")
    check(
        ws_ran.returncode == 0 and out(ws_ran) == "workspace\n",
        f"`run -p wsapp` of a workspace member with a dev-dependency failed: {err(ws_ran)[:300]}",
    )
    for arguments in (["build", ".", "-p", "wsapp", "--offline"], ["test", ".", "-p", "wsapp", "--offline", "--locked"]):
        result = run_in(wsroot, *arguments)
        check(
            result.returncode == 0,
            f"`burdin {' '.join(arguments)}` failed on a path-only workspace: {err(result)[:300]}",
        )
    check(not (wsroot / "apps" / "wsapp" / "burdin.lock").exists(), "a workspace member wrote its own lockfile")

print(f"Checked dependency tables, features, and targets ({checks} checks)")

