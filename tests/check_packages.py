#!/usr/bin/env python3
"""Checks `burdin add` and `burdin.lock` (stage 3, issues #238 and #239; spec/packages.md).

Needs a built driver (BURDIN selects it, like tests/run_tests.py) and `git` on PATH. Every repository is a local one
reached through a `file://` URL, and BURDIN_HOME points into a temporary directory, so nothing touches the network
or the user's git cache.

What it checks:
  * `burdin add --path` writes the documented `[dependencies]` line and lockfile, the package then runs, and adding
    the same name again replaces the line (PKG11-PKG13);
  * a graph of path packages alone writes no lockfile until one exists (PKG6);
  * `--locked` passes while the lockfile matches and, after a manifest changes, fails with exit status 1 for
    `build`, `run`, `check`, and `test`, names the difference, and leaves the file alone; without `--locked` the
    next build rewrites it (PKG8-PKG9);
  * `burdin add --git --tag` pins the tag's commit with a checksum, the program builds from that checkout, and a
    branch dependency stays on its locked commit after the branch moves until the lockfile is removed or the branch
    is added again (PKG3-PKG7, PKG13);
  * `--locked` with a git dependency the lockfile does not record fails;
  * a changed checkout fails its checksum, and deleting it fetches it again (PKG7);
  * failures leave burdin.toml and burdin.lock unchanged: a missing path, a directory that is not a package, an
    unknown tag, an invalid name, a registry name, no manifest, and usage errors (exit status 2) (PKG14);
  * `--manifest-path` edits another package, and a lockfile of a newer format is refused (PKG10);
  * official packages (PKG15-PKG18): `name = true` builds and runs, also through another official package, with the
    golden lockfile (`source = "official"` and a checksum this script recomputes from PKG7); `burdin add <name>` writes
    `name = true`; a changed official package fails `--locked`, naming it, and a plain build re-pins it; `= false`,
    an unknown name, no packages directory, and `burdin add` of an unknown name fail with their messages; a `use` of
    an undeclared official package gets the help line; and the lookup order of PKG16 (`BURDIN_PACKAGES`, then
    `<exe dir>/../packages`, then `<exe dir>/packages`) works from a copy of the driver. The packages are the
    fixtures in tests/packages/official, so the check does not depend on the real packages.
"""

import hashlib
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

import harness

problems = []
checks = 0


def check(condition: bool, message: str) -> None:
    global checks
    checks += 1
    if not condition:
        problems.append(message)


burdin = harness.require_burdin()
if harness.which("git") is None:
    print("check_packages.py needs `git` on PATH", file=sys.stderr)
    sys.exit(1)

HEADER = (
    "# burdin.lock: the exact packages this package builds with. It is generated by burdin;\n"
    "# do not edit it by hand.\n"
    "version = 1\n"
)


def lock_entry(name, version=None, deps=(), git=None, official_checksum=None):
    lines = ["", "[[package]]", f'name = "{name}"']
    if version is not None:
        lines.append(f'version = "{version}"')
    if official_checksum is not None:
        lines.append('source = "official"')
        lines.append(f'checksum = "{official_checksum}"')
    if git is not None:
        url, reference, commit, checksum = git
        lines.append(f'git = "{url}"')
        if reference is not None:
            lines.append(f'{reference[0]} = "{reference[1]}"')
        lines.append(f'commit = "{commit}"')
        lines.append(f'checksum = "{checksum}"')
    lines.append("dependencies = [" + ", ".join(f'"{d}"' for d in deps) + "]")
    return "\n".join(lines) + "\n"


def tree_checksum(directory: Path) -> str:
    """PKG7: `sha256:` and the SHA-256 of every file's path, a NUL, its length, a NUL, and its bytes, by path."""
    files = []
    for path in directory.rglob("*"):
        relative = path.relative_to(directory).as_posix()
        if path.is_file() and relative.split("/")[0] not in (".git", "target"):
            files.append((relative, path))
    digest = hashlib.sha256()
    for relative, path in sorted(files):
        data = path.read_bytes()
        digest.update(relative.encode() + b"\0" + str(len(data)).encode() + b"\0" + data)
    return "sha256:" + digest.hexdigest()


def package(directory: Path, name: str, version: str, module: str, body: str) -> Path:
    (directory / "src").mkdir(parents=True, exist_ok=True)
    harness.write_text(directory / "burdin.toml", f'[package]\nname = "{name}"\nversion = "{version}"\n')
    harness.write_text(directory / "src" / f"{module}.bd", body)
    return directory


def snapshot(directory: Path):
    """The manifest and lockfile texts, to prove a failed command changed neither."""
    def read(name):
        path = directory / name
        return harness.read_bytes(path) if path.exists() else None

    return read("burdin.toml"), read("burdin.lock")


with harness.temporary_dir("burdin-packages-") as work:
    env = dict(os.environ)
    env["BURDIN_HOME"] = str(work / "home")
    env.update(
        GIT_AUTHOR_NAME="burdin",
        GIT_AUTHOR_EMAIL="burdin@example.com",
        GIT_COMMITTER_NAME="burdin",
        GIT_COMMITTER_EMAIL="burdin@example.com",
        GIT_CONFIG_NOSYSTEM="1",
        GIT_CONFIG_GLOBAL=str(work / "gitconfig"),
    )
    harness.write_text(work / "gitconfig", "")

    def burdin_in(cwd, *arguments):
        return harness.run([burdin, *arguments], cwd=cwd, env=env)

    def git(cwd, *arguments):
        result = subprocess.run(
            ["git", "-c", "init.defaultBranch=main", "-c", "commit.gpgsign=false", "-c", "tag.gpgsign=false",
             "-c", "core.autocrlf=false", *arguments],
            cwd=str(cwd), env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False,
        )
        if result.returncode != 0:
            raise SystemExit(f"git {' '.join(arguments)} failed: {harness.text(result.stderr)}")
        return harness.text(result.stdout).strip()

    def out(result):
        return harness.text(result.stdout).replace("\r", "")

    def err(result):
        return harness.text(result.stderr).replace("\r", "")

    app = package(work / "app", "app", "0.1.0", "main", "use greet.answer\n\nfn main() {\n    println(answer().to_string())\n}\n")
    greet = package(work / "greet", "greet", "0.1.0", "greet", "fn answer(): i32 {\n    42\n}\n")
    original_manifest = '[package]\nname = "app"\nversion = "0.1.0"\n'

    # --- A path dependency through `burdin add` -----------------------------------------------------------------
    added = burdin_in(app, "add", "--path", "../greet")
    check(added.returncode == 0, f"`burdin add --path ../greet` failed: {err(added)[:400]}")
    check(out(added) == "Added dependency `greet` (path ../greet)\n", f"`burdin add` printed {out(added)!r}")
    manifest = original_manifest + '\n[dependencies]\ngreet = { path = "../greet" }\n'
    check(harness.read_text(app / "burdin.toml") == manifest, "burdin.toml after `add --path` is not the golden text")
    path_lock = HEADER + lock_entry("app", "0.1.0", ["greet"]) + lock_entry("greet", "0.1.0")
    check(
        (app / "burdin.lock").is_file() and harness.read_text(app / "burdin.lock") == path_lock,
        "burdin.lock after `add --path` is not the golden text",
    )
    ran = burdin_in(app, "run", ".", "--locked")
    check(ran.returncode == 0 and out(ran) == "42\n", f"`burdin run . --locked` gave {ran.returncode}: {out(ran)!r} {err(ran)[:300]}")

    again = burdin_in(app, "add", "greet", "--path", "../greet")
    check(again.returncode == 0, f"adding `greet` again failed: {err(again)[:300]}")
    check(out(again) == "Replaced dependency `greet` (path ../greet)\n", f"re-adding printed {out(again)!r}")
    check(harness.read_text(app / "burdin.toml") == manifest, "re-adding the same dependency changed burdin.toml")

    # A graph of path packages with no lockfile writes none.
    plain = package(work / "plain", "plain", "1.0.0", "main", "use greet.answer\n\nfn main() {\n    println(answer().to_string())\n}\n")
    harness.write_text(plain / "burdin.toml", '[package]\nname = "plain"\n\n[dependencies]\ngreet = "../greet"\n')
    built = burdin_in(plain, "run", ".", "--locked")
    check(built.returncode == 0 and out(built) == "42\n", f"a path-only package without a lockfile failed: {err(built)[:300]}")
    check(not (plain / "burdin.lock").exists(), "a path-only package without a lockfile got one")

    # --- A stale lockfile ----------------------------------------------------------------------------------------
    harness.write_text(greet / "burdin.toml", '[package]\nname = "greet"\nversion = "0.2.0"\n')
    for command in (["build", "."], ["run", "."], ["check", "."], ["test", "."]):
        before = snapshot(app)
        stale = burdin_in(app, *command, "--locked")
        check(stale.returncode == 1, f"`burdin {' '.join(command)} --locked` on a stale lockfile exited {stale.returncode}")
        check("burdin.lock is out of date" in err(stale), f"`{command[0]} --locked` does not say the lockfile is stale")
        check(
            "`greet` is version 0.2.0 but burdin.lock records 0.1.0" in err(stale),
            f"`{command[0]} --locked` does not name the difference: {err(stale)[:300]}",
        )
        check(snapshot(app) == before, f"`{command[0]} --locked` changed burdin.toml or burdin.lock")
    rebuilt = burdin_in(app, "build", ".")
    check(rebuilt.returncode == 0, f"`burdin build .` did not update a stale lockfile: {err(rebuilt)[:300]}")
    check(
        harness.read_text(app / "burdin.lock") == HEADER + lock_entry("app", "0.1.0", ["greet"]) + lock_entry("greet", "0.2.0"),
        "the rewritten lockfile does not record version 0.2.0",
    )
    check(burdin_in(app, "check", ".", "--locked").returncode == 0, "`check --locked` fails on an updated lockfile")

    # --- A git dependency ----------------------------------------------------------------------------------------
    repo = package(work / "colors-repo", "colors", "1.0.0", "colors", "fn shade(): i32 {\n    1\n}\n")
    git(repo, "init", "--quiet")
    git(repo, "add", ".")
    git(repo, "commit", "--quiet", "-m", "one")
    git(repo, "tag", "v1")
    v1 = git(repo, "rev-parse", "HEAD")
    harness.write_text(repo / "src" / "colors.bd", "fn shade(): i32 {\n    2\n}\n")
    git(repo, "commit", "--quiet", "-am", "two")
    two = git(repo, "rev-parse", "HEAD")
    url = repo.resolve().as_uri()

    harness.write_text(
        app / "src" / "main.bd",
        "use greet.answer\nuse colors.shade\n\nfn main() {\n    println(answer().to_string())\n    println(shade().to_string())\n}\n",
    )
    added = burdin_in(app, "add", "--git", url, "--tag", "v1")
    check(added.returncode == 0, f"`burdin add --git --tag v1` failed: {err(added)[:400]}")
    check(
        out(added) == f"Added dependency `colors` (git {url}, tag v1, commit {v1[:12]})\n",
        f"`burdin add --git` printed {out(added)!r}",
    )
    manifest_git = manifest + f'colors = {{ git = "{url}", tag = "v1" }}\n'
    check(harness.read_text(app / "burdin.toml") == manifest_git, "burdin.toml after `add --git` is not the golden text")
    lock_text = harness.read_text(app / "burdin.lock")
    found = re.search(r'checksum = "(sha256:[0-9a-f]{64})"', lock_text)
    check(found is not None, f"the git package has no sha256 checksum in burdin.lock:\n{lock_text}")
    checksum = found.group(1) if found else ""
    expected_lock = (
        HEADER
        + lock_entry("app", "0.1.0", ["colors", "greet"])
        + lock_entry("colors", "1.0.0", git=(url, ("tag", "v1"), v1, checksum))
        + lock_entry("greet", "0.2.0")
    )
    check(lock_text == expected_lock, f"burdin.lock after `add --git` is not the golden text:\n{lock_text}")
    checkouts = work / "home" / "git" / "checkouts"
    checkout = next(checkouts.glob(f"*/{v1}"), None) if checkouts.is_dir() else None
    check(checkout is not None and (checkout / "burdin.toml").is_file(), "the tag's commit is not checked out in the cache")
    check(checkout is None or not (checkout / ".git").exists(), "a checkout has a .git directory")
    ran = burdin_in(app, "run", ".", "--locked")
    check(ran.returncode == 0 and out(ran) == "42\n1\n", f"the tag dependency did not build from v1: {out(ran)!r} {err(ran)[:300]}")

    # A branch dependency stays on its locked commit when the branch moves.
    switched = burdin_in(app, "add", "colors", "--git", url, "--branch", "main")
    check(switched.returncode == 0, f"switching to `--branch main` failed: {err(switched)[:300]}")
    check(out(switched).startswith("Replaced dependency `colors`"), f"switching printed {out(switched)!r}")
    check(f'commit = "{two}"' in harness.read_text(app / "burdin.lock"), "the branch did not lock its head commit")
    harness.write_text(repo / "src" / "colors.bd", "fn shade(): i32 {\n    3\n}\n")
    git(repo, "commit", "--quiet", "-am", "three")
    three = git(repo, "rev-parse", "HEAD")
    pinned = burdin_in(app, "run", ".", "--locked")
    check(pinned.returncode == 0 and out(pinned) == "42\n2\n", f"a moved branch changed the build: {out(pinned)!r} {err(pinned)[:300]}")
    check(f'commit = "{two}"' in harness.read_text(app / "burdin.lock"), "a build moved the locked commit")

    # Without a lockfile, `--locked` refuses; a plain build resolves the branch again.
    (app / "burdin.lock").unlink()
    refused = burdin_in(app, "build", ".", "--locked")
    check(refused.returncode == 1, f"`--locked` without a lockfile exited {refused.returncode}")
    check("is not in burdin.lock" in err(refused), f"`--locked` without a lockfile said: {err(refused)[:300]}")
    check(not (app / "burdin.lock").exists(), "`--locked` wrote a lockfile")
    moved = burdin_in(app, "run", ".")
    check(moved.returncode == 0 and out(moved) == "42\n3\n", f"re-resolving the branch gave {out(moved)!r} {err(moved)[:300]}")
    check(f'commit = "{three}"' in harness.read_text(app / "burdin.lock"), "the re-resolved lockfile does not pin the new head")

    # Adding the branch again moves it to the branch's new head.
    harness.write_text(repo / "src" / "colors.bd", "fn shade(): i32 {\n    4\n}\n")
    git(repo, "commit", "--quiet", "-am", "four")
    four = git(repo, "rev-parse", "HEAD")
    readded = burdin_in(app, "add", "colors", "--git", url, "--branch", "main")
    check(
        readded.returncode == 0
        and out(readded) == f"Replaced dependency `colors` (git {url}, branch main, commit {four[:12]})\n",
        f"re-adding the branch printed {out(readded)!r} {err(readded)[:300]}",
    )
    check(f'commit = "{four}"' in harness.read_text(app / "burdin.lock"), "re-adding a branch did not move it to its head")

    # A changed checkout fails its checksum; deleting it fetches it again.
    checkout = next(checkouts.glob(f"*/{four}"), None)
    check(checkout is not None, "the new head is not checked out")
    if checkout is not None:
        harness.write_text(checkout / "src" / "colors.bd", "fn shade(): i32 {\n    99\n}\n")
        tampered = burdin_in(app, "build", ".")
        check(tampered.returncode == 1, f"a tampered checkout built (exit {tampered.returncode})")
        check("do not match the checksum in burdin.lock" in err(tampered), f"the checksum error said: {err(tampered)[:300]}")
        shutil.rmtree(checkout)
        refetched = burdin_in(app, "run", ".", "--locked")
        check(refetched.returncode == 0 and out(refetched) == "42\n4\n", f"refetching gave {out(refetched)!r} {err(refetched)[:300]}")

    # --- Failures change nothing ---------------------------------------------------------------------------------
    (work / "notapackage").mkdir()
    for arguments, status, needle in [
        (["add", "--path", "../missing"], 1, "cannot open"),
        (["add", "--path", "../notapackage"], 1, "is not a Burdin package"),
        (["add", "--git", url, "--tag", "nope"], 1, "has no tag nope"),
        (["add", "my-lib", "--path", "../greet"], 1, "is not a valid dependency name"),
        (["add", "fn", "--path", "../greet"], 1, "reserved word"),
        (["add", "jsn"], 2, "no package registry"),
        (["add", "jsn@1.0"], 2, "no package registry"),
        (["add"], 2, "needs a dependency"),
        (["add", "--path", "../greet", "--git", url], 2, "not both"),
        (["add", "--path", "../greet", "--tag", "v1"], 2, "only to `--git`"),
        (["add", "--bogus"], 2, "unknown option"),
    ]:
        before = snapshot(app)
        result = burdin_in(app, *arguments)
        shown = " ".join(arguments)
        check(result.returncode == status, f"`burdin {shown}` exited {result.returncode}, expected {status}")
        check(needle in err(result), f"`burdin {shown}` did not say {needle!r}: {err(result)[:300]}")
        check(snapshot(app) == before, f"a failed `burdin {shown}` changed burdin.toml or burdin.lock")
    helped = burdin_in(app, "add", "--help")
    check(helped.returncode == 0 and "burdin add" in out(helped), "`burdin add --help` does not print the usage")

    outside = burdin_in(work, "add", "--path", "greet")
    check(outside.returncode == 1 and "no burdin.toml" in err(outside), f"`add` outside a package said: {err(outside)[:300]}")

    # --manifest-path edits another package's manifest.
    elsewhere = burdin_in(work, "add", "--path", "greet", "--manifest-path", str(Path("plain") / "burdin.toml"))
    check(elsewhere.returncode == 0, f"`add --manifest-path` failed: {err(elsewhere)[:300]}")
    check(out(elsewhere) == "Replaced dependency `greet` (path ../greet)\n", f"`add --manifest-path` printed {out(elsewhere)!r}")
    check(
        harness.read_text(plain / "burdin.toml") == '[package]\nname = "plain"\n\n[dependencies]\ngreet = { path = "../greet" }\n',
        "`add --manifest-path` wrote the wrong manifest",
    )
    check((plain / "burdin.lock").is_file(), "`burdin add` did not write a lockfile for a path-only package")

    # A lockfile of a newer format is refused, not overwritten.
    harness.write_text(plain / "burdin.lock", "version = 2\n")
    newer = burdin_in(plain, "build", ".")
    check(newer.returncode == 1 and "version 2 is not supported" in err(newer), f"a newer lockfile said: {err(newer)[:300]}")
    check(harness.read_text(plain / "burdin.lock") == "version = 2\n", "a newer lockfile was overwritten")

    # --- Official packages (PKG15-PKG18) ---------------------------------------------------------------------------
    official = work / "official"
    shutil.copytree(harness.TESTS / "packages" / "official", official)
    official_env = dict(env)
    official_env["BURDIN_PACKAGES"] = str(official)

    def official_in(cwd, *arguments, environment=None):
        return harness.run([burdin, *arguments], cwd=cwd, env=environment or official_env)

    use_shout = "use shout.loud\n\nfn main() {\n    println(loud().to_string())\n}\n"
    oapp = package(work / "oapp", "oapp", "0.1.0", "main", use_shout)
    oapp_manifest = '[package]\nname = "oapp"\nversion = "0.1.0"\n'
    added = official_in(oapp, "add", "shout")
    check(added.returncode == 0, f"`burdin add shout` failed: {err(added)[:400]}")
    check(out(added) == "Added dependency `shout` (official)\n", f"`burdin add shout` printed {out(added)!r}")
    check(
        harness.read_text(oapp / "burdin.toml") == oapp_manifest + "\n[dependencies]\nshout = true\n",
        "burdin.toml after `add shout` is not the golden text",
    )

    def official_lock():
        return (
            HEADER
            + lock_entry("mark", "0.1.0", official_checksum=tree_checksum(official / "mark"))
            + lock_entry("oapp", "0.1.0", ["shout"])
            + lock_entry("shout", "0.2.0", ["mark"], official_checksum=tree_checksum(official / "shout"))
        )

    check(
        harness.read_text(oapp / "burdin.lock") == official_lock(),
        "burdin.lock after `add shout` is not the golden text:\n" + harness.read_text(oapp / "burdin.lock"),
    )
    ran = official_in(oapp, "run", ".", "--locked")
    check(ran.returncode == 0 and out(ran) == "34\n", f"an official package did not build: {out(ran)!r} {err(ran)[:300]}")
    again = official_in(oapp, "add", "shout")
    check(out(again) == "Replaced dependency `shout` (official)\n", f"re-adding an official package printed {out(again)!r}")
    check(harness.read_text(oapp / "burdin.toml").count("shout") == 1, "re-adding an official package repeated its line")

    # A manifest written by hand: `--locked` wants a lockfile, a plain build writes the golden one.
    hand = package(work / "hand", "oapp", "0.1.0", "main", use_shout)
    harness.write_text(hand / "burdin.toml", oapp_manifest + "\n[dependencies]\nshout = true\n")
    unlocked = official_in(hand, "build", ".", "--locked")
    check(
        unlocked.returncode == 1 and "there is no burdin.lock" in err(unlocked),
        f"--locked without a lockfile said: {err(unlocked)[:300]}",
    )
    check(not (hand / "burdin.lock").exists(), "`--locked` wrote a lockfile for an official package")
    built = official_in(hand, "build", ".")
    check(built.returncode == 0, f"a hand-written `shout = true` did not build: {err(built)[:300]}")
    check(harness.read_text(hand / "burdin.lock") == official_lock(), "a plain build did not write the golden lockfile")

    # An official package that changed (a newer compiler brings newer ones) is a difference, not a corrupt checkout.
    harness.write_text(official / "mark" / "src" / "mark.bd", "fn bang(): i32 {\n    40\n}\n")
    before = snapshot(oapp)
    changed = official_in(oapp, "build", ".", "--locked")
    check(changed.returncode == 1, f"`--locked` accepted a changed official package (exit {changed.returncode})")
    check(
        "`mark` is an official package whose files are not the ones burdin.lock pinned" in err(changed),
        f"`--locked` did not name the changed official package: {err(changed)[:400]}",
    )
    check(snapshot(oapp) == before, "`--locked` changed burdin.toml or burdin.lock for an official package")
    repinned = official_in(oapp, "run", ".")
    check(
        repinned.returncode == 0 and out(repinned) == "41\n",
        f"a changed official package gave {out(repinned)!r} {err(repinned)[:300]}",
    )
    check(harness.read_text(oapp / "burdin.lock") == official_lock(), "a plain build did not re-pin the changed official package")
    check(official_in(oapp, "check", ".", "--locked").returncode == 0, "`check --locked` fails on a re-pinned official package")

    # Mistakes in the manifest.
    bad = package(work / "bad", "bad", "0.1.0", "main", "fn main() {\n}\n")
    bad_manifest = '[package]\nname = "bad"\n\n[dependencies]\n'
    for line, needle in [
        ("shout = false\n", "`shout = false` means nothing"),
        ("jsn = true\n", "dependency `jsn = true`: it is not an official package; the official packages are: mark, shout"),
        ("jsn = true\n", '{ git = "..." }'),
        ("shout = yes\n", "`true` for an official package"),
        ('shout = { version = "1.0" }\n', "no package registry"),
    ]:
        harness.write_text(bad / "burdin.toml", bad_manifest + line)
        result = official_in(bad, "build", ".")
        check(result.returncode == 1, f"`{line.strip()}` exited {result.returncode}, expected 1")
        check(needle in err(result), f"`{line.strip()}` did not say {needle!r}: {err(result)[:300]}")
        check(not (bad / "burdin.lock").exists(), f"`{line.strip()}` wrote a lockfile")
    missing_env = dict(env)
    missing_env["BURDIN_PACKAGES"] = str(work / "no-such-folder")
    harness.write_text(bad / "burdin.toml", bad_manifest + "shout = true\n")
    result = official_in(bad, "build", ".", environment=missing_env)
    check(
        result.returncode == 1 and "found no packages directory" in err(result) and "BURDIN_PACKAGES" in err(result),
        f"`shout = true` without a packages directory said: {err(result)[:300]}",
    )

    # `burdin add` of a name that is not official, and an official name with a git reference.
    for arguments, status, needle in [
        (["add", "jsn"], 2, "the official packages are: mark, shout"),
        (["add", "jsn"], 2, "no package registry"),
        (["add", "jsn@1.0"], 2, "no package registry"),
        (["add", "shout", "--tag", "v1"], 2, "only to `--git`"),
    ]:
        before = snapshot(oapp)
        result = official_in(oapp, *arguments)
        shown = " ".join(arguments)
        check(result.returncode == status, f"`burdin {shown}` exited {result.returncode}, expected {status}")
        check(needle in err(result), f"`burdin {shown}` did not say {needle!r}: {err(result)[:300]}")
        check(snapshot(oapp) == before, f"a failed `burdin {shown}` changed burdin.toml or burdin.lock")
    nothing = official_in(oapp, "add", "shout", environment=missing_env)
    check(
        nothing.returncode == 2 and "has no official packages" in err(nothing),
        f"`add shout` with no packages said: {err(nothing)[:300]}",
    )

    # A `use` of an official package the manifest does not declare keeps its error and gains the help line.
    forgot = package(work / "forgot", "forgot", "0.1.0", "main", use_shout)
    undeclared = official_in(forgot, "check", ".", "--width", "0")
    check(
        undeclared.returncode == 1 and "unknown module `shout.loud`" in err(undeclared),
        f"an undeclared `use shout` said: {err(undeclared)[:300]}",
    )
    check(
        "`shout` is an official package: add `shout = true` to [dependencies] or run `burdin add shout`" in err(undeclared),
        f"an undeclared `use shout` has no help line: {err(undeclared)[:400]}",
    )
    other = package(work / "other", "other", "0.1.0", "main", "use jsn.loud\n\nfn main() {\n}\n")
    unknown = official_in(other, "check", ".", "--width", "0")
    check(unknown.returncode == 1 and "unknown module `jsn.loud`" in err(unknown), f"`use jsn` said: {err(unknown)[:300]}")
    check("official package" not in err(unknown), "`use jsn` got a help line about official packages")
    declared = official_in(forgot, "add", "shout")
    check(declared.returncode == 0, f"`burdin add shout` after the error failed: {err(declared)[:300]}")
    fixed = official_in(forgot, "run", ".")
    check(
        fixed.returncode == 0 and out(fixed) == "41\n",
        f"the `use shout` program did not run after `add`: {out(fixed)!r} {err(fixed)[:300]}",
    )

    # The lookup order (PKG16), from copies of the driver: `bin/burdin` with `packages/` beside `bin/`, and `burdin`
    # with `packages/` beside it. BURDIN_PACKAGES is not set, so only the executable's own surroundings can find them.
    plain_env = dict(env)
    plain_env.pop("BURDIN_PACKAGES", None)
    executable = "burdin" + Path(burdin).suffix
    for layout, exe_dir, packages_at in (
        ("installed", work / "inst" / "bin", work / "inst" / "packages"),
        ("unpacked", work / "unpacked", work / "unpacked" / "packages"),
    ):
        exe_dir.mkdir(parents=True)
        shutil.copy2(burdin, exe_dir / executable)
        shutil.copytree(harness.TESTS / "packages" / "official", packages_at)
        located = package(work / f"located-{layout}", "located", "0.1.0", "main", use_shout)
        result = harness.run([exe_dir / executable, "add", "shout"], cwd=located, env=plain_env)
        check(result.returncode == 0, f"the {layout} layout did not find the official packages: {err(result)[:300]}")
        ran = harness.run([exe_dir / executable, "run", "."], cwd=located, env=plain_env)
        check(ran.returncode == 0 and out(ran) == "34\n", f"the {layout} layout did not build: {out(ran)!r} {err(ran)[:300]}")

print(f"Checked `burdin add` and burdin.lock ({checks} checks)")

if harness.report_problems(problems):
    sys.exit(1)
print("No problems.")
